"""Host functions on a device that ships bytecode only.

``@host`` compiles a function from its source, and an APK carries ``.pyc``
files without the ``.py`` they came from. So the build keeps the source of
each ``@host`` definition -- nothing else -- in one generated module beside the
app, and ``host`` reads it there when ``inspect`` finds none. The function is
then compiled exactly as on the desktop, with the same constants and messages.

A definition is found by its module and the line it starts on (its first
decorator): a function's code object keeps that line in any ``.pyc``, and no
two definitions start on one line. Run by the build with the interpreter that
compiles the app's bytecode::

    python -m pycompose.ui._sources SOURCE_DIR OUTPUT_FILE
"""

from __future__ import annotations

import ast
import importlib
import pprint
import sys
import textwrap
from pathlib import Path
from types import FunctionType

TABLE = "__pycompose_host__"
"""The generated module, importable from the root of the app's sources."""


def key(module: str, line: int) -> str:
    """Name one definition.

    Args:
        module: Its module's dotted name.
        line: The line its first decorator stands on.

    Returns:
        ``module:line``.
    """
    return f"{module}:{line}"


def host_sources(root: Path) -> dict[str, dict[str, str]]:
    """The source of every ``@host`` definition under ``root``.

    Args:
        root: The app's source directory.

    Returns:
        Per definition: the file it is in and its dedented source.
    """
    table: dict[str, dict[str, str]] = {}
    for path in sorted(root.rglob("*.py")):
        relative = path.relative_to(root)
        if any(
            part.startswith(".") or part == "__pycache__" for part in relative.parts
        ):
            continue
        text = path.read_text(encoding="utf-8")
        if "host" not in text:
            continue
        lines = text.splitlines(keepends=True)
        parts = relative.with_suffix("").parts
        module = ".".join(parts[:-1] if parts[-1] == "__init__" else parts)
        for node in ast.walk(ast.parse(text, str(path))):
            if isinstance(node, ast.FunctionDef) and any(
                _is_host(decorator) for decorator in node.decorator_list
            ):
                first = node.decorator_list[0].lineno
                table[key(module, first)] = {
                    "file": relative.as_posix(),
                    "source": textwrap.dedent(
                        "".join(lines[first - 1 : node.end_lineno])
                    ),
                }
    return table


def _is_host(decorator: ast.expr) -> bool:
    return (isinstance(decorator, ast.Name) and decorator.id == "host") or (
        isinstance(decorator, ast.Attribute) and decorator.attr == "host"
    )


def built_source(function: FunctionType) -> tuple[str, str]:
    """A definition's source as the build kept it, for a function with none.

    Args:
        function: The decorated function.

    Returns:
        Its file, relative to the app's sources, and its source.

    Raises:
        OSError: If the build kept no source for it.
    """
    try:
        sources: dict[str, dict[str, str]] = importlib.import_module(TABLE).SOURCES
    except ImportError:
        sources = {}
    found = sources.get(key(function.__module__, function.__code__.co_firstlineno))
    if found is None:
        raise OSError(
            f"no source for host function {function.__qualname__}: "
            "build the app with pycompose build, which keeps it"
        )
    return found["file"], found["source"]


def main(argv: list[str]) -> int:
    """Write the table for one source directory.

    Args:
        argv: The source directory and the module file to write.

    Returns:
        The exit status.
    """
    root, output = Path(argv[0]), Path(argv[1])
    output.parent.mkdir(parents=True, exist_ok=True)
    table = pprint.pformat(host_sources(root), width=88, sort_dicts=True)
    output.write_text(
        "# GENERATED by pycompose.ui._sources -- DO NOT EDIT.\n"
        '"""The source of each @host definition, for a device without .py files."""\n\n'
        f"SOURCES: dict[str, dict[str, str]] = {table}\n",
        encoding="utf-8",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
