"""One SVG becomes the launcher icon: adaptive layers, themed form, legacy icon.

``[app] icon = "icon.svg"`` names the artwork; its view box is the adaptive
icon's 108-unit foreground canvas, so artwork drawn on the standard grid keeps
its safe zone. ``[app] icon_background`` is the background colour. The same
paths form the monochrome layer Android tints for themed icons, and a 48dp
vector composes both for devices before adaptive icons.

The converter accepts the part of SVG a launcher icon needs -- paths, rects,
circles, polygons and groups, filled or stroked with solid colours -- and
refuses anything else by name rather than drawing it wrong.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from xml.etree.ElementTree import Element

from defusedxml import ElementTree
from defusedxml.common import DefusedXmlException

from pycompose.cli.project import Project, ProjectError, project_path

_SVG = "{http://www.w3.org/2000/svg}"
_HEX = re.compile(r"#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})")
_NAMED = {"black": "#000000", "white": "#FFFFFF"}
_PAINTED = ("fill", "fill-opacity", "fill-rule", "stroke", "stroke-width")
_PLAIN = {"stroke-linecap", "stroke-linejoin", "id", "class", "opacity"}
_RES = "host/src/main/res"


@dataclass(frozen=True)
class _Path:
    data: str
    paint: dict[str, str]


def icon_files(project: Project) -> dict[str, bytes]:
    """The launcher icon resources ``[app] icon`` describes, by Android path.

    Args:
        project: The app.

    Returns:
        Resource files relative to the Android project; none without an icon.

    Raises:
        ProjectError: If the icon or its background is invalid.
    """
    app = project.table("app")
    source = app.get("icon")
    if source is None:
        return {}
    if not isinstance(source, str):
        raise ProjectError("app.icon must be a path to an SVG file")
    background = _color(app.get("icon_background", "#FFFFFF"), "app.icon_background")
    path = project_path(project.root, source)
    if not path.is_file() or path.suffix.lower() != ".svg":
        raise ProjectError("app.icon must name an SVG file in the project", path=source)
    box, paths = _parse(path)
    header = (
        f"<!-- Generated by pycompose from [app] icon ({source}); "
        "edits are discarded. -->\n"
    )
    foreground = _vector(box, paths, 108)
    monochrome = _vector(box, [_Path(p.data, _white(p.paint)) for p in paths], 108)
    legacy = _vector(box, [_Path(_rect(box), {"fill": background}), *paths], 48)
    adaptive = (
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@drawable/app_icon_background" />\n'
        '    <foreground android:drawable="@drawable/app_icon_foreground" />\n'
        '    <monochrome android:drawable="@drawable/app_icon_monochrome" />\n'
        "</adaptive-icon>\n"
    )
    files = {
        "drawable/app_icon_foreground.xml": foreground,
        "drawable/app_icon_monochrome.xml": monochrome,
        "drawable/app_icon_background.xml": _vector(
            (0, 0, 108, 108), [_Path("M0,0h108v108H0z", {"fill": background})], 108
        ),
        "drawable/app_icon.xml": legacy,
        "drawable-v26/app_icon.xml": adaptive,
    }
    return {f"{_RES}/{name}": (header + text).encode() for name, text in files.items()}


def _parse(path: Path) -> tuple[tuple[float, float, float, float], list[_Path]]:
    try:
        root = ElementTree.parse(path).getroot()
    except (ElementTree.ParseError, DefusedXmlException) as exc:
        raise ProjectError("app.icon is not valid SVG", reason=str(exc)) from exc
    if root.tag != f"{_SVG}svg":
        raise ProjectError("app.icon must be an <svg> document")
    box = tuple(
        float(v) for v in re.split(r"[\s,]+", root.get("viewBox", "").strip()) if v
    )
    if len(box) != 4 or box[2] <= 0 or box[3] <= 0:
        raise ProjectError("app.icon needs a viewBox with a positive size")
    paths: list[_Path] = []
    _walk(root, {"fill": "#000000"}, paths)
    if not paths:
        raise ProjectError("app.icon draws nothing")
    return (box[0], box[1], box[2], box[3]), paths


def _walk(node: Element, inherited: dict[str, str], out: list[_Path]) -> None:
    for child in node:
        tag = child.tag.removeprefix(_SVG)
        if tag in {"title", "desc", "metadata", "defs"} and not len(child):
            continue
        unknown = set(child.attrib) - {*_PAINTED, *_PLAIN, *_GEOMETRY.get(tag, ())}
        if tag not in {"g", *_GEOMETRY} or unknown or "transform" in child.attrib:
            what = f"<{tag}>" + (
                f" with {', '.join(sorted(unknown))}" if unknown else ""
            )
            raise ProjectError(
                f"app.icon uses {what}, which the converter does not draw"
            )
        paint = {
            **inherited,
            **{k: child.attrib[k] for k in _PAINTED if k in child.attrib},
        }
        if tag == "g":
            _walk(child, paint, out)
        else:
            out.append(_Path(_geometry(tag, child), paint))


_GEOMETRY = {
    "path": ("d",),
    "rect": ("x", "y", "width", "height"),
    "circle": ("cx", "cy", "r"),
    "polygon": ("points",),
}


def _geometry(tag: str, node: Element) -> str:
    def number(name: str) -> float:
        return float(node.get(name, "0"))

    if tag == "path":
        return node.get("d", "")
    if tag == "rect":
        x, y, w, h = (number(n) for n in ("x", "y", "width", "height"))
        return f"M{_n(x)},{_n(y)}h{_n(w)}v{_n(h)}h{_n(-w)}z"
    if tag == "circle":
        cx, cy, r = (number(n) for n in ("cx", "cy", "r"))
        return (
            f"M{_n(cx - r)},{_n(cy)}a{_n(r)},{_n(r)} 0 1 0 {_n(2 * r)},0"
            f"a{_n(r)},{_n(r)} 0 1 0 {_n(-2 * r)},0z"
        )
    points = re.split(r"[\s,]+", node.get("points", "").strip())
    pairs = [f"{points[i]},{points[i + 1]}" for i in range(0, len(points) - 1, 2)]
    return "M" + "L".join(pairs) + "z"


def _vector(box: tuple[float, float, float, float], paths: list[_Path], dp: int) -> str:
    x, y, width, height = box
    lines = [
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{dp}dp"',
        f'    android:height="{dp}dp"',
        f'    android:viewportWidth="{_n(width)}"',
        f'    android:viewportHeight="{_n(height)}">',
    ]
    shifted = x or y
    if shifted:
        lines.append(
            f'    <group android:translateX="{_n(-x)}" android:translateY="{_n(-y)}">'
        )
    indent = "    " * (2 if shifted else 1)
    lines.extend(indent + _path(path) for path in paths)
    if shifted:
        lines.append("    </group>")
    return "\n".join([*lines, "</vector>"]) + "\n"


def _path(path: _Path) -> str:
    paint = path.paint
    attributes = [f'android:pathData="{path.data}"']
    fill = paint.get("fill", "#000000")
    if fill != "none":
        attributes.append(f'android:fillColor="{_color(fill, "app.icon fill")}"')
        if "fill-opacity" in paint:
            attributes.append(f'android:fillAlpha="{paint["fill-opacity"]}"')
        if paint.get("fill-rule") == "evenodd":
            attributes.append('android:fillType="evenOdd"')
    if paint.get("stroke", "none") != "none":
        attributes.append(
            f'android:strokeColor="{_color(paint["stroke"], "app.icon stroke")}"'
        )
        attributes.append(f'android:strokeWidth="{paint.get("stroke-width", "1")}"')
    return "<path " + " ".join(attributes) + " />"


def _white(paint: dict[str, str]) -> dict[str, str]:
    """The monochrome layer: Android tints it, so only coverage matters."""
    return {
        key: "#FFFFFF" if key in {"fill", "stroke"} and value != "none" else value
        for key, value in paint.items()
    }


def _rect(box: tuple[float, float, float, float]) -> str:
    x, y, width, height = box
    return f"M{_n(x)},{_n(y)}h{_n(width)}v{_n(height)}h{_n(-width)}z"


def _color(value: object, key: str) -> str:
    text = _NAMED.get(str(value).lower(), str(value))
    match = _HEX.fullmatch(text)
    if match is None:
        raise ProjectError(f"{key} must be a #RRGGBB colour", value=str(value))
    digits = match.group(1)
    if len(digits) == 3:
        digits = "".join(c * 2 for c in digits)
    return f"#{digits.upper()}"


def _n(value: float) -> str:
    return f"{value:g}"
