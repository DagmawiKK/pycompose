"""Embedding policy: how the generator ships string data into each target.

One module owns literal embedding for every language the generator emits. The
shape of each embedding is deliberately *bounded* rather than merely correct:
a `+`-chain in Kotlin is one call on the previous result per link, so a large
contract overflows the compiler stack (a prior CI failure is the regression
test that refuses it), and a Python adjacent-literal block must stay flat so
runtime imports never gained a parse step they did not need.

Chunks are cut by content, not by position: a fixed width shifted every chunk
after an insertion, so one new catalog entry rewrote thousands of committed
lines. A cut follows a comma whose preceding window hashes to zero, so an edit
changes the chunks around it and the cuts after it fall where they fell.
"""

from __future__ import annotations

import json
import zlib

GENERATED_NOTICE = "GENERATED by tools/schema/gen.py -- DO NOT EDIT."
"""Header stamp every generated artifact carries, everywhere the code emits."""

CHUNK_MIN = 24
"""No cut before this many characters, which bounds the number of chunks."""

CHUNK_MAX = 64
"""A cut is forced here, which bounds a generated line's width."""

CUT_ODDS = 4
"""One comma in this many, past the minimum, ends a chunk."""

WINDOW = 16
"""Characters before a comma that decide whether it ends a chunk."""


def python_string(value: str) -> str:
    """Return a quoted Python token that keeps embedded JSON unescaped."""
    if '"' in value and "'" not in value:
        escaped = json.dumps(value)[1:-1].replace('\\"', '"')
        return f"'{escaped}'"
    return json.dumps(value)


def kotlin_string(value: str) -> str:
    """Return a quoted Kotlin token that escapes template dollars."""
    return json.dumps(value, ensure_ascii=False).replace("$", "\\$")


def chunks(raw: str) -> list[str]:
    """Cut one string where its content says, so edits stay local.

    Args:
        raw: The text to embed, compact JSON in practice.

    Returns:
        Consecutive slices joining back to ``raw``.
    """
    cuts, start = [], 0
    for index, char in enumerate(raw):
        size = index + 1 - start
        window = raw[max(start, index + 1 - WINDOW) : index + 1].encode()
        if size >= CHUNK_MAX or (
            char == "," and size >= CHUNK_MIN and zlib.crc32(window) % CUT_ODDS == 0
        ):
            cuts.append(raw[start : index + 1])
            start = index + 1
    return [*cuts, raw[start:]] if start < len(raw) else cuts


def python_adjacent_statements(raw: str, indent: int = 8) -> list[str]:
    """Split one string into adjacent Python literals, each on its own line."""
    pad = " " * indent
    return [f"{pad}{python_string(chunk)}" for chunk in chunks(raw)]


def kotlin_joined_statements(raw: str, indent: int = 12) -> list[str]:
    """Split one string into a flat Kotlin list body, joined once by the caller."""
    pad = " " * indent
    return [f"{pad}{kotlin_string(chunk)}," for chunk in chunks(raw)]
