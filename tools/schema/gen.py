#!/usr/bin/env python3
"""SSOT codegen: derive ``schema/ir.schema.json`` and Python validator tables.

Run from anywhere inside the repo:

    python tools/schema/gen.py          # regenerate derived artifacts
    python tools/schema/gen.py --check  # fail on drift (CI / pre-commit)

Pure stdlib, fully deterministic: no timestamps, no environment reads, keys
sorted. Generated files are committed and must never be hand-edited.
"""

from __future__ import annotations

import argparse
import json
import keyword
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

SCHEMA_PATH = ROOT / "schema" / "components.json"
IR_SCHEMA_PATH = ROOT / "schema" / "ir.schema.json"
BUNDLED_SCHEMA_PATH = ROOT / "pycompose" / "schema" / "ir.schema.json"
VALIDATORS_PATH = ROOT / "pycompose" / "ir" / "generated_validators.py"
PAYLOADS_PATH = ROOT / "pycompose" / "bridge" / "generated_payloads.py"
KOTLIN_MODELS_PATH = (
    ROOT / "android/ir/src/main/kotlin/com/pycompose/ir/generated/UiModels.kt"
)
KOTLIN_REGISTRY_PATH = (
    ROOT / "android/ir/src/main/kotlin/com/pycompose/ir/generated/IrContract.kt"
)

GENERATED_NOTICE = "GENERATED by tools/schema/gen.py -- DO NOT EDIT."

JSON_SCHEMA_DRAFT = "http://json-schema.org/draft-07/schema#"

PROP_TYPE_VOCABULARY = frozenset(
    {
        "actionId",
        "boolean",
        "color",
        "dp",
        "durationMs",
        "enum",
        "integer",
        "modifier",
        "number",
        "string",
    }
)

STABILITIES = frozenset({"beta", "experimental", "stable"})

SEMVER_PATTERN = re.compile(r"^\d+\.\d+\.\d+$")


def _die(message: str) -> None:
    raise SystemExit(f"gen.py: {message}")


def load_registry() -> dict:
    """Read and structurally validate ``schema/components.json``."""
    try:
        raw = SCHEMA_PATH.read_text(encoding="utf-8")
    except OSError as exc:
        _die(f"cannot read {SCHEMA_PATH}: {exc}")
    try:
        registry = json.loads(raw)
    except json.JSONDecodeError as exc:
        _die(f"invalid JSON in {SCHEMA_PATH}: {exc}")
    _validate_registry(registry)
    return registry


def _validate_registry(registry: dict) -> None:
    for key in ("schemaVersion", "minLibraryVersion", "components", "actions"):
        if key not in registry:
            _die(f"missing top-level key {key!r} in components.json")
    if not isinstance(registry["schemaVersion"], str):
        _die("schemaVersion must be a string")
    _require_semver(registry["schemaVersion"], "schemaVersion")
    min_library = registry["minLibraryVersion"]
    if not isinstance(min_library, str):
        _die("minLibraryVersion must be a string")
    _require_semver(min_library, "minLibraryVersion")

    components = registry["components"]
    if not isinstance(components, dict) or not components:
        _die("'components' must be a non-empty object")
    for name, comp in sorted(components.items()):
        _validate_component(name, comp)

    actions = registry["actions"]
    if not isinstance(actions, dict):
        _die("'actions' must be an object")
    for action_id, action in sorted(actions.items()):
        _validate_action(action_id, action)
    _validate_action_refs(registry)
    modifiers = registry.get("modifiers", {})
    if not isinstance(modifiers, dict):
        _die("'modifiers' must be an object")
    for name, modifier in sorted(modifiers.items()):
        if not isinstance(modifier, dict) or not isinstance(
            modifier.get("props"), dict
        ):
            _die(f"modifier {name!r} needs a props object")
        for prop_name, prop in sorted(modifier["props"].items()):
            _validate_prop(name, prop_name, prop)


def _require_semver(value: str, field: str) -> None:
    if SEMVER_PATTERN.fullmatch(value) is None:
        _die(f"{field} must be MAJOR.MINOR.PATCH semver, got {value!r}")


def _validate_action_refs(registry: dict) -> None:
    declared = set(registry["actions"])
    for name, comp in sorted(registry["components"].items()):
        for prop_name, prop in sorted(comp["props"].items()):
            if prop.get("type") != "actionId" or "default" not in prop:
                continue
            default = prop["default"]
            if default not in declared:
                _die(
                    f"component {name}.{prop_name} defaults to action "
                    f"{default!r} which is not declared in 'actions'"
                )


def _validate_component(name: str, comp: dict) -> None:
    if not isinstance(comp, dict):
        _die(f"component {name!r} must be an object")
    if not isinstance(comp.get("category"), str) or not comp["category"]:
        _die(f"component {name!r} needs a non-empty 'category'")
    if comp.get("stability") not in STABILITIES:
        _die(f"component {name!r} has unknown stability {comp.get('stability')!r}")
    props = comp.get("props")
    if not isinstance(props, dict):
        _die(f"component {name!r} needs a 'props' object")
    for prop_name, prop in sorted(props.items()):
        _validate_prop(name, prop_name, prop)
    children = comp.get("children")
    if not isinstance(children, dict):
        _die(f"component {name!r} needs a 'children' object")
    if not isinstance(children.get("allowed"), bool):
        _die(f"component {name!r} needs children.allowed as a boolean")
    if "kind" in children and not isinstance(children["kind"], str):
        _die(f"component {name!r} children.kind must be a string")
    if "min" in children and not isinstance(children["min"], int):
        _die(f"component {name!r} children.min must be an integer")


def _validate_prop(name: str, prop_name: str, prop: dict) -> None:
    if not isinstance(prop, dict):
        _die(f"prop {name}.{prop_name} must be an object")
    ptype = prop.get("type")
    if ptype not in PROP_TYPE_VOCABULARY:
        _die(
            f"prop {name}.{prop_name} has unknown type {ptype!r}; "
            f"vocabulary: {sorted(PROP_TYPE_VOCABULARY)}"
        )
    if ptype == "enum":
        values = prop.get("values")
        if (
            not isinstance(values, list)
            or not values
            or not all(isinstance(value, str) for value in values)
        ):
            _die(f"enum prop {name}.{prop_name} needs a non-empty string 'values' list")
    if "required" in prop and not isinstance(prop["required"], bool):
        _die(f"prop {name}.{prop_name} 'required' must be a boolean")
    for bound in ("minimum", "maximum"):
        if bound in prop and (
            not isinstance(prop[bound], int | float)
            or isinstance(prop[bound], bool)
            or (isinstance(prop[bound], float) and not math.isfinite(prop[bound]))
        ):
            _die(f"prop {name}.{prop_name} {bound} must be finite numeric data")
    if "minimum" in prop and "maximum" in prop and prop["minimum"] > prop["maximum"]:
        _die(f"prop {name}.{prop_name} minimum exceeds maximum")


def _validate_action(action_id: str, action: dict) -> None:
    if not isinstance(action, dict):
        _die(f"action {action_id!r} must be an object")
    payload = action.get("payload", {})
    if not isinstance(payload, dict):
        _die(f"action {action_id!r} 'payload' must be an object")
    for field_name, field in sorted(payload.items()):
        is_invalid = (
            not isinstance(field, dict) or field.get("type") not in PROP_TYPE_VOCABULARY
        )
        if is_invalid:
            _die(
                f"action {action_id!r} payload field {field_name!r} has an invalid type"
            )
        _validate_prop(action_id, field_name, field)


def render_payloads(registry: dict) -> str:
    """Generate Python input payload contracts from registry action fields."""
    actions = registry["actions"]
    names = {
        action_id: "".join(
            part[:1].upper() + part[1:]
            for part in re.findall(r"[A-Za-z0-9]+", action_id)
        )
        + "Payload"
        for action_id in sorted(actions)
    }
    if len(set(names.values())) != len(names) or any(
        not name.isidentifier() for name in names.values()
    ):
        _die("action ids must produce unique Python payload names")
    imports = {"TypedDict"}
    declarations = []
    simple_types = {
        "string": "str",
        "color": "str",
        "actionId": "str",
        "boolean": "bool",
        "integer": "int",
        "durationMs": "int",
        "number": "int | float",
        "dp": "int | float",
        "modifier": "dict[str, JsonValue]",
    }
    uses_json = False
    for action_id, name in names.items():
        fields = {}
        for field_name, prop in sorted(actions[action_id].get("payload", {}).items()):
            if prop["type"] == "enum":
                imports.add("Literal")
                annotation = (
                    "Literal["
                    + ", ".join(json.dumps(value) for value in sorted(prop["values"]))
                    + "]"
                )
            else:
                annotation = simple_types[prop["type"]]
            uses_json |= prop["type"] == "modifier"
            if not prop.get("required", False):
                imports.add("NotRequired")
                annotation = f"NotRequired[{annotation}]"
            fields[field_name] = annotation
        payload = actions[action_id].get("payload", {})
        if all(
            field.isidentifier() and not keyword.iskeyword(field) for field in payload
        ):
            body = "\n".join(
                f"    {field}: {annotation}" for field, annotation in fields.items()
            )
            declarations.append(f"class {name}(TypedDict):\n" + (body or "    pass"))
        else:
            declarations.append(
                f'{name} = TypedDict(\n    "{name}",\n    {{\n'
                + "\n".join(
                    f"        {json.dumps(field)}: {annotation},"
                    for field, annotation in fields.items()
                )
                + "\n    },\n)"
            )
    return (
        f"# {GENERATED_NOTICE}\n"
        '"""Generated host action input payload contracts."""\n\n'
        "from __future__ import annotations\n\n"
        f"from typing import {', '.join(sorted(imports))}\n"
        + ("\nfrom pycompose.core.props import JsonValue\n" if uses_json else "")
        + "\n__all__ = [\n"
        + "".join(f'    "{name}",\n' for name in sorted(names.values()))
        + "]\n\n\n"
        + "\n\n\n".join(declarations)
        + "\n"
    )


def render_ir_schema(registry: dict) -> str:
    """Render the derived JSON Schema for canonical IR snapshots."""
    components = registry["components"]
    action_ids = sorted(registry.get("actions", {}))
    component_defs = {
        f"C_{name}": _component_schema(name, comp, action_ids)
        for name, comp in sorted(components.items())
    }
    ir_schema = {
        "$schema": JSON_SCHEMA_DRAFT,
        "$id": "https://pycompose.dev/schema/ir.schema.json",
        "title": "PyCompose IR: canonical snapshot",
        "type": "object",
        "required": ["version", "schemaVersion", "root"],
        "properties": {
            "version": {"type": "string"},
            "schemaVersion": {"const": registry["schemaVersion"]},
            "root": {"$ref": "#/definitions/Node"},
        },
        "definitions": {
            "Node": _node_schema(sorted(component_defs)),
            "ModifierOperation": {
                "anyOf": [
                    {
                        "type": "object",
                        "required": [
                            "type",
                            *sorted(
                                key
                                for key, prop in modifier["props"].items()
                                if prop.get("required")
                            ),
                        ],
                        "properties": {
                            "type": {"const": name},
                            **{
                                key: _prop_schema(prop, action_ids)
                                for key, prop in sorted(modifier["props"].items())
                            },
                        },
                        "additionalProperties": False,
                    }
                    for name, modifier in sorted(registry.get("modifiers", {}).items())
                ]
                or [False]
            },
            **component_defs,
        },
    }
    return json.dumps(ir_schema, indent=2, sort_keys=True) + "\n"


def _node_schema(component_refs: list[str]) -> dict:
    return {
        "type": "object",
        "required": ["id", "type", "props"],
        "properties": {
            "id": {"type": "string", "minLength": 1},
            "type": {"type": "string"},
            "props": {"type": "object"},
            "children": {
                "type": "array",
                "items": {"$ref": "#/definitions/Node"},
            },
        },
        "allOf": [
            {"anyOf": [{"$ref": f"#/definitions/{ref}"} for ref in component_refs]}
        ],
    }


def _component_schema(name: str, comp: dict, action_ids: list[str]) -> dict:
    props = sorted(comp["props"].items())
    props_schema = {
        "type": "object",
        "properties": {
            prop_name: _prop_schema(prop, action_ids) for prop_name, prop in props
        },
        "additionalProperties": False,
    }
    required = [prop_name for prop_name, prop in props if prop.get("required")]
    if required:
        props_schema["required"] = required

    node_properties: dict[str, object] = {
        "type": {"const": name},
        "props": props_schema,
    }
    children = comp.get("children", {})
    if children.get("allowed"):
        minimum = children.get("min", 0)
        if minimum:
            node_properties["children"] = {"minItems": minimum}
    else:
        node_properties["children"] = False
    return {"type": "object", "properties": node_properties}


def _prop_schema(prop: dict, action_ids: list[str]) -> dict:
    ptype = prop["type"]
    if ptype in {"string", "color"}:
        value = {"type": "string"}
    elif ptype in {"integer", "durationMs"}:
        value = {"type": "integer"}
    elif ptype in {"number", "dp"}:
        value = {"type": "number"}
    elif ptype == "boolean":
        value = {"type": "boolean"}
    elif ptype == "enum":
        value = {"enum": sorted(prop["values"])}
    elif ptype == "actionId":
        value = {"enum": action_ids}
    elif ptype == "modifier":
        value = {
            "type": "object",
            "properties": {
                "operations": {
                    "type": "array",
                    "items": {"$ref": "#/definitions/ModifierOperation"},
                }
            },
        }
    else:
        _die(f"unsupported prop type {ptype!r}")
    if "default" in prop:
        value["default"] = prop["default"]
    for bound in ("minimum", "maximum"):
        if bound in prop:
            value[bound] = prop[bound]
    return value


def render_validators(registry: dict) -> str:
    """Render typed runtime tables directly from the SSOT registry."""
    action_ids = sorted(registry.get("actions", {}))
    ids = [json.dumps(action_id) for action_id in action_ids]
    if len(ids) == 1:
        action_tuple = f"({ids[0]},)"
    elif ids:
        action_tuple = "(" + ", ".join(ids) + ")"
    else:
        action_tuple = "()"
    raw = json.dumps(registry, sort_keys=True, separators=(",", ":"))
    # Adjacent literals embed the entire registry without a runtime file read.
    chunks = [
        _python_string(raw[index : index + 50]) for index in range(0, len(raw), 50)
    ]
    literals = "\n".join(f"        {chunk}" for chunk in chunks)
    body = (
        f"# {GENERATED_NOTICE}\n"
        '"""Generated component, prop, children and action validation tables."""\n\n'
        "from __future__ import annotations\n\n"
        "import json\n\n"
        "from pycompose.core.registry_types import Registry\n\n"
        '__all__ = [\n    "KNOWN_ACTION_IDS",\n    "MIN_LIBRARY_VERSION",\n'
        '    "MIN_SCHEMA_VERSION",\n    "REGISTRY",\n    "SCHEMA_VERSION",\n]\n\n'
        f"SCHEMA_VERSION: str = {json.dumps(registry['schemaVersion'])}\n"
        "MIN_SCHEMA_VERSION: str = SCHEMA_VERSION\n"
        f"MIN_LIBRARY_VERSION: str = {json.dumps(registry['minLibraryVersion'])}\n"
        f"KNOWN_ACTION_IDS: tuple[str, ...] = {action_tuple}\n"
        f"REGISTRY: Registry = Registry.from_mapping(\n    json.loads(\n{literals}\n"
        "    )\n)\n"
    )
    return body


def _python_string(value: str) -> str:
    # Choose quotes that preserve embedded JSON without unnecessary escaping.
    if '"' in value and "'" not in value:
        escaped = json.dumps(value)[1:-1].replace('\\"', '"')
        return f"'{escaped}'"
    return json.dumps(value)


def _read(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8")
    except OSError:
        return None


def _kt_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False).replace("$", "\\$")


def _kt_field(name: str) -> str:
    if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) is None:
        _die(f"invalid Kotlin contract identifier: {name!r}")
    return f"`{name}`"


def _kt_type(prop: dict) -> str:
    return {
        "string": "String",
        "color": "String",
        "actionId": "String",
        "enum": "String",
        "boolean": "Boolean",
        "integer": "Long",
        "durationMs": "Long",
        "number": "Double",
        "dp": "Double",
        "modifier": "JsonObject",
    }[prop["type"]]


def _kt_default(prop: dict) -> str:
    if "default" not in prop:
        return "" if prop.get("required", False) else " = null"
    value = prop["default"]
    if isinstance(value, str):
        return " = " + _kt_string(value)
    if isinstance(value, bool):
        return " = " + str(value).lower()
    if prop["type"] in {"integer", "durationMs"}:
        return f" = {value}L"
    if prop["type"] in {"number", "dp"}:
        return f" = {float(value)}"
    _die("unsupported Kotlin prop default")
    return ""


def _kt_props(name: str, props: dict, base: str = "UiProps") -> list[str]:
    lines = ["@Serializable"]
    if not props:
        return [*lines, f"data object {name} : {base}", ""]
    lines.append(f"data class {name}(")
    for field, prop in sorted(props.items()):
        nullable = (
            "?" if not prop.get("required", False) and "default" not in prop else ""
        )
        override = "override " if field == "modifier" and base == "UiProps" else ""
        lines.append(
            f"    {override}val {_kt_field(field)}: "
            f"{_kt_type(prop)}{nullable}{_kt_default(prop)},"
        )
    return [*lines, f") : {base}", ""]


def render_kotlin_models(registry: dict) -> str:
    """Generate sealed per-component models without Android types or reflection."""
    lines = [
        f"// {GENERATED_NOTICE}",
        "package com.pycompose.ir.generated",
        "",
        "import kotlinx.serialization.SerialName",
        "import kotlinx.serialization.Serializable",
        "import kotlinx.serialization.json.JsonObject",
        "",
        "@Serializable",
        "sealed interface UiNode {",
        "    val id: String",
        "    val props: UiProps",
        "    val children: List<UiNode>",
        "    val componentType: String",
        "}",
        "",
        "sealed interface UiProps {",
        "    val modifier: JsonObject? get() = null",
        "}",
        "",
        "@Serializable",
        "data class IRRoot(",
        "    val version: String,",
        "    val schemaVersion: String,",
        "    val root: UiNode,",
        "    val metadata: JsonObject? = null,",
        ")",
        "",
    ]
    names = set(registry["components"])
    generated_names = {"UiNode", "UiProps", "IRRoot", "ActionPayload"} | {
        name + "Props" for name in names
    }
    if names & generated_names:
        _die("component names collide with generated Kotlin contract types")
    for name, spec in sorted(registry["components"].items()):
        if re.fullmatch(r"[A-Z][A-Za-z0-9_]*", name) is None:
            _die(f"component name must be PascalCase for Kotlin generation: {name!r}")
        _kt_field(name)
        lines.extend(_kt_props(name + "Props", spec["props"]))
        lines.extend(
            [
                "@Serializable",
                f"@SerialName({_kt_string(name)})",
                f"data class {name}(",
                "    override val id: String,",
                f"    override val props: {name}Props,",
            ]
        )
        if spec["children"]["allowed"]:
            lines.append("    override val children: List<UiNode> = emptyList(),")
        lines.append(") : UiNode {")
        if not spec["children"]["allowed"]:
            lines.append("    override val children: List<UiNode> get() = emptyList()")
        lines.extend(
            [
                f"    override val componentType: String get() = {_kt_string(name)}",
                "}",
                "",
            ]
        )
    lines.extend(["sealed interface ActionPayload", ""])
    payload_names = set()
    for action, spec in sorted(registry["actions"].items()):
        name = (
            "".join(
                part[:1].upper() + part[1:]
                for part in re.findall(r"[A-Za-z0-9]+", action)
            )
            + "Payload"
        )
        _kt_field(name)
        if name in names | generated_names | payload_names:
            _die("action ids must produce unique Kotlin payload names")
        payload_names.add(name)
        lines.extend(_kt_props(name, spec.get("payload", {}), "ActionPayload"))
    return "\n".join(lines)


def _kt_rules(props: dict) -> list[str]:
    lines = []
    for name, prop in sorted(props.items()):
        args = [
            _kt_string(prop["type"]),
            f"required = {str(prop.get('required', False)).lower()}",
        ]
        if "values" in prop:
            args.append(
                "values = setOf("
                + ", ".join(_kt_string(value) for value in prop["values"])
                + ")"
            )
        args.extend(
            f"{field} = {float(prop[field])}"
            for field in ("minimum", "maximum")
            if field in prop
        )
        lines.append(
            f"                {_kt_string(name)} to PropertyRule({', '.join(args)}),"
        )
    return lines


def render_kotlin_registry(registry: dict) -> str:
    """Generate validation registrations from the same registry as Python."""
    lines = [
        f"// {GENERATED_NOTICE}",
        "package com.pycompose.ir.generated",
        "",
        "import com.pycompose.ir.ComponentRule",
        "import com.pycompose.ir.PropertyRule",
        "",
        "object IrContract {",
        "    const val SCHEMA_VERSION: String = "
        + _kt_string(registry["schemaVersion"]),
        "    const val MIN_SCHEMA_VERSION: String = SCHEMA_VERSION",
        "    const val MIN_LIBRARY_VERSION: String = "
        + _kt_string(registry["minLibraryVersion"]),
        "    val actionIds: Set<String> = setOf("
        + ", ".join(_kt_string(name) for name in sorted(registry["actions"]))
        + ")",
        "    val components: Map<String, ComponentRule> = mapOf(",
    ]
    for name, spec in sorted(registry["components"].items()):
        lines.extend(
            [
                f"        {_kt_string(name)} to ComponentRule(",
                "            childrenAllowed = "
                + str(spec["children"]["allowed"]).lower()
                + ",",
                f"            minimumChildren = {spec['children'].get('min', 0)},",
                "            props = mapOf(",
                *_kt_rules(spec["props"]),
                "            ),",
                "        ),",
            ]
        )
    lines.extend(
        ["    )", "    val modifiers: Map<String, Map<String, PropertyRule>> = mapOf("]
    )
    for name, spec in sorted(registry.get("modifiers", {}).items()):
        lines.extend(
            [
                f"        {_kt_string(name)} to mapOf(",
                *_kt_rules(spec["props"]),
                "        ),",
            ]
        )
    return "\n".join([*lines, "    )", "}", ""])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Regenerate schema/ir.schema.json and "
            "pycompose/ir/generated_validators.py."
        )
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify derived artifacts are up to date; exit non-zero on drift (CI).",
    )
    args = parser.parse_args(argv)
    registry = load_registry()
    artifacts = {
        IR_SCHEMA_PATH: render_ir_schema(registry),
        BUNDLED_SCHEMA_PATH: render_ir_schema(registry),
        VALIDATORS_PATH: render_validators(registry),
        PAYLOADS_PATH: render_payloads(registry),
        KOTLIN_MODELS_PATH: render_kotlin_models(registry),
        KOTLIN_REGISTRY_PATH: render_kotlin_registry(registry),
    }
    for path in (KOTLIN_MODELS_PATH, KOTLIN_REGISTRY_PATH):
        artifacts[
            ROOT / "pycompose/templates/android" / path.relative_to(ROOT / "android")
        ] = artifacts[path]
    for fixture in sorted((ROOT / "pycompose/testing/fixtures").glob("*.json")):
        relative = Path("ir/src/test/resources") / fixture.name
        contents = fixture.read_text(encoding="utf-8")
        artifacts[ROOT / "android" / relative] = contents
        artifacts[ROOT / "pycompose/templates/android" / relative] = contents
    if args.check:
        drifted = [
            str(path) for path, expected in artifacts.items() if _read(path) != expected
        ]
        if drifted:
            for path in drifted:
                print(f"gen.py: drift detected: {path} is out of date", file=sys.stderr)
            return 1
        return 0
    for path, content in artifacts.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    print(f"gen.py: regenerated {len(artifacts)} artifact(s)")
    return 0


