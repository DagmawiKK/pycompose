JSON_SCHEMA_DRAFT = "http://json-schema.org/draft-07/schema#"

PROP_TYPE_VOCABULARY = frozenset(
    {
        "actionId",
        "boolean",
        "color",
        "dp",
        "durationMs",
        "enum",
        "integer",
        "modifier",
        "value",
        "number",
        "string",
        "resource",
    }
)

STABILITIES = frozenset({"beta", "experimental", "stable"})

SLOT_KINDS = frozenset({"content", "items"})
"""How a slot's subtree composes: nodes in order, or lazy list items."""

CONSUMERS = frozenset({"paddingValues"})
"""Slot scopes the adapter consumes on the subtree's behalf."""

SLOT_NAME = re.compile(r"^[a-z][A-Za-z0-9]*$")
"""Named slots are ``camelCase`` on the wire, so no spelling is invented."""

NATIVE_PARAMETER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

DOTTED_NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*$")
"""A Kotlin package or type name: a dotted path of simple identifiers."""

RESERVED_SLOTS = frozenset({"children", "id", "modifier", "props"})

#: Keys a slot entry may carry. Anything else is a typo, not a convention.
SLOT_KEYS = frozenset({"native", "kind", "nullable", "consume"})

#: Keys an interaction entry may carry. Anything else is a typo.
INTERACTION_KEYS = frozenset({"native", "observations"})

#: The closed set of interaction kinds the host can observe.
INTERACTION_KINDS = frozenset({"press", "focus", "hover"})

#: Keys a state entry may carry. Anything else is a typo.
STATE_KEYS = frozenset({"native", "kind", "value", "report", "dismiss"})

#: Keys a prop's provider entry may carry. Anything else is a typo.
PROVIDER_KEYS = frozenset({"native", "returns"})

#: The closed set of state families the host can create, drive and report.
STATE_KINDS = frozenset({"drawer", "sheet"})

#: The state a reported payload field may carry: one lowerCamel field.
REPORTED_FIELD = re.compile(r"[a-z][A-Za-z0-9]*")

SEMVER_PATTERN = re.compile(r"^\d+\.\d+\.\d+$")


def _die(message: str) -> NoReturn:
    """Abort codegen with a message.

    Typed ``NoReturn`` rather than ``None`` because every call site is a guard:
    ``if not isinstance(x, dict): _die(...)`` only narrows ``x`` if the compiler
    knows the branch does not continue.
    """
    raise SystemExit(f"gen.py: {message}")


def load_registry() -> dict[str, Any]:
    """Read and structurally validate ``schema/components.json``."""
    try:
        raw = SCHEMA_PATH.read_text(encoding="utf-8")
    except OSError as exc:
        _die(f"cannot read {SCHEMA_PATH}: {exc}")
    try:
        registry: dict[str, Any] = json.loads(raw)
    except json.JSONDecodeError as exc:
        _die(f"invalid JSON in {SCHEMA_PATH}: {exc}")
    _validate_registry(registry)
    return registry


def _validate_registry(registry: dict[str, Any]) -> None:
    for key in ("schemaVersion", "minLibraryVersion", "components", "actions"):
        if key not in registry:
            _die(f"missing top-level key {key!r} in components.json")
    if not isinstance(registry["schemaVersion"], str):
        _die("schemaVersion must be a string")
    _require_semver(registry["schemaVersion"], "schemaVersion")
    min_library = registry["minLibraryVersion"]
    if not isinstance(min_library, str):
        _die("minLibraryVersion must be a string")
    _require_semver(min_library, "minLibraryVersion")

    components = registry["components"]
    if not isinstance(components, dict) or not components:
        _die("'components' must be a non-empty object")
    for name, comp in sorted(components.items()):
        _validate_component(name, comp)
    _validate_versions(registry)

    actions = registry["actions"]
    if not isinstance(actions, dict):
        _die("'actions' must be an object")
    for action_id, action in sorted(actions.items()):
        _validate_action(action_id, action)
    _validate_action_refs(registry)
    _validate_effects(registry.get("effects", {}))
    _validate_lifecycle(registry.get("lifecycle", {}))
    modifiers = registry.get("modifiers", {})
    if not isinstance(modifiers, dict):
        _die("'modifiers' must be an object")
    for name, modifier in sorted(modifiers.items()):
        if not isinstance(modifier, dict) or not isinstance(
            modifier.get("props"), dict
        ):
            _die(f"modifier {name!r} needs a props object")
        for prop_name, prop in sorted(modifier["props"].items()):
            _validate_prop(name, prop_name, prop)
    from pycompose.schema.codegen.values import validate_definitions

    validate_definitions(registry)


def _validate_effects(effects: object) -> None:
    """Validate the declared effect kinds and their payload contracts."""
    if not isinstance(effects, dict):
        _die("'effects' must be an object")
    for kind, effect in sorted(effects.items()):
        if re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", kind) is None:
            _die(f"effect kind {kind!r} must be a PascalCase identifier")
        _validate_action(kind, effect)


def _validate_lifecycle(lifecycle: object) -> None:
    """Validate host-initiated lifecycle events and their payload contracts."""
    if not isinstance(lifecycle, dict):
        _die("'lifecycle' must be an object")
    for event, body in sorted(lifecycle.items()):
        if re.fullmatch(r"on[A-Z][A-Za-z0-9]*", event) is None:
            _die(f"lifecycle event {event!r} must be an onXxx identifier")
        _validate_action(event, body)


def _require_semver(value: str, field: str) -> None:
    if not isinstance(value, str) or SEMVER_PATTERN.fullmatch(value) is None:
        _die(f"{field} must be MAJOR.MINOR.PATCH semver, got {value!r}")


def _version_key(value: str) -> tuple[int, ...]:
    return tuple(map(int, value.split(".")))


def _supported(registry: dict[str, Any]) -> list[str]:
    versions: list[str] = registry.get(
        "supportedSchemaVersions", [registry["schemaVersion"]]
    )
    return versions


def _validate_versions(registry: dict[str, Any]) -> None:
    supported = _supported(registry)
    if (
        not isinstance(supported, list)
        or not supported
        or registry["schemaVersion"] not in supported
    ):
        _die("supportedSchemaVersions must include the current schema")
    for version in supported:
        _require_semver(version, "supportedSchemaVersions")
    if len(set(supported)) != len(supported):
        _die("supportedSchemaVersions must be unique")
    if max(supported, key=_version_key) != registry["schemaVersion"]:
        _die("schemaVersion must be the newest supported schema")
    for spec in registry["components"].values():
        for definition in [spec, *spec["props"].values()]:
            if "since" in definition:
                _require_semver(definition["since"], "since")
                if definition["since"] not in supported:
                    _die("since must refer to a supported schema")


def _validate_action_refs(registry: dict[str, Any]) -> None:
    declared = set(registry["actions"])
    for name, comp in sorted(registry["components"].items()):
        for prop_name, prop in sorted(comp["props"].items()):
            if prop.get("type") != "actionId" or "default" not in prop:
                continue
            default = prop["default"]
            if default not in declared:
                _die(
                    f"component {name}.{prop_name} defaults to action "
                    f"{default!r} which is not declared in 'actions'"
                )


def _validate_opt_in(name: str, comp: dict[str, Any]) -> None:
    """Check a component's declared opt-in markers are usable annotation names.

    Mirrors ``valueTypes.*.optIn``: the pin decided which markers a declaration
    needs, and this only refuses a list that is malformed. Sorted and unique
    keeps the generated ``@file:OptIn`` byte-stable.

    Args:
        name: Component name, for error messages.
        comp: The component's raw schema entry.
    """
    markers = comp.get("optIn", [])
    if markers != sorted(set(markers)) or not all(
        isinstance(marker, str) and marker for marker in markers
    ):
        _die(f"component {name!r} optIn must be sorted, unique annotation names")


def _validate_component(name: str, comp: dict[str, Any]) -> None:
    if not isinstance(comp, dict):
        _die(f"component {name!r} must be an object")
    if not isinstance(comp.get("category"), str) or not comp["category"]:
        _die(f"component {name!r} needs a non-empty 'category'")
    package = comp.get("package")
    if not isinstance(package, str) or DOTTED_NAME.fullmatch(package) is None:
        _die(f"component {name!r} needs a dotted 'package' the pin declares it in")
    if comp.get("stability") not in STABILITIES:
        _die(f"component {name!r} has unknown stability {comp.get('stability')!r}")
    _validate_opt_in(name, comp)
    _validate_scope(name, comp)
    props = comp.get("props")
    if not isinstance(props, dict):
        _die(f"component {name!r} needs a 'props' object")
    for prop_name, prop in sorted(props.items()):
        _validate_prop(name, prop_name, prop)
    children = comp.get("children")
    if not isinstance(children, dict):
        _die(f"component {name!r} needs a 'children' object")
    _validate_children(name, children)
    _validate_slots(name, props, children, comp.get("slots", {}))
    _validate_interaction(
        name, props, children, comp.get("slots", {}), comp.get("interaction")
    )
    _validate_state(name, props, children, comp.get("slots", {}), comp.get("state"))


def _validate_children(name: str, children: dict[str, Any]) -> None:
    """Check a component's children declaration and the scope it provides.

    Args:
        name: Component name, for error messages.
        children: The component's raw ``children`` object.
    """
    if not isinstance(children.get("allowed"), bool):
        _die(f"component {name!r} needs children.allowed as a boolean")
    if children.get("kind", "content") not in SLOT_KINDS:
        _die(
            f"component {name!r} children.kind must be one of "
            + ", ".join(sorted(SLOT_KINDS))
        )
    if "min" in children and not isinstance(children["min"], int):
        _die(f"component {name!r} children.min must be an integer")
    natively = children.get("native")
    if natively is not None and not (
        isinstance(natively, str) and NATIVE_PARAMETER.match(natively)
    ):
        _die(f"component {name!r} children.native must be a parameter name")
    if children.get("consume") not in {None, *CONSUMERS}:
        _die(
            f"component {name!r} children.consume must be one of "
            + ", ".join(sorted(CONSUMERS))
        )
    provides = children.get("provides")
    if provides is None:
        return
    from pycompose.schema.codegen.adapters import SCOPES

    if provides not in SCOPES:
        _die(
            f"component {name!r} children.provides must be one of "
            + ", ".join(sorted(SCOPES))
        )
    if children.get("consume") is not None:
        _die(f"component {name!r} children cannot consume and provide a scope")
    if children.get("kind", "content") != "content":
        _die(f"component {name!r} children.provides needs the content kind")


def _validate_scope(name: str, comp: dict[str, Any]) -> None:
    """Check a component's declared receiver against the scope vocabulary.

    A component the pin declares as an extension on a composition scope cannot
    be looked up like a plain one: its receiver exists only inside the parent
    lambda that provides it, so the adapter registers through the matching
    scoped method. The vocabulary is closed, and the fact itself is re-derived
    from the pinned inventory by ``check_upstream``.

    Args:
        name: Component name, for error messages.
        comp: The component's schema entry.
    """
    scope = comp.get("scope")
    if scope is None:
        return
    from pycompose.schema.codegen.adapters import SCOPES

    if scope not in SCOPES:
        _die(f"component {name!r} scope must be one of " + ", ".join(sorted(SCOPES)))


def _validate_interaction(
    name: str,
    props: dict[str, Any],
    children: dict[str, Any],
    slots: object,
    interaction: object,
) -> None:
    """Check a component's declared interaction source against the vocabulary.

    The interaction source is the host's, not the app's: the schema names the
    native parameter it fills and, per interaction kind, the prop whose action
    observes that kind, and the generator omits those props from the app's
    arguments. Each observed payload is declared once, on its prop, exactly as
    every other host-originated callback declares it.

    Args:
        name: Component name, for error messages.
        props: The component's props; every observed prop must be one of them.
        children: The component's ``children`` object, whose native parameter
            the interaction source must not reuse.
        slots: The component's declared slots, which claim their own natives.
        interaction: The raw ``interaction`` object, or None.
    """
    if interaction is None:
        return
    where = f"component {name!r} interaction"
    if not isinstance(interaction, dict):
        _die(f"{where} must be an object")
    unknown = sorted(set(interaction) - INTERACTION_KEYS)
    if unknown:
        _die(f"{where} has unknown keys: {', '.join(unknown)}")
    injected = interaction.get("native")
    if not isinstance(injected, str) or not NATIVE_PARAMETER.match(injected):
        _die(f"{where}: 'native' must be a parameter name")
    natives = {children.get("native", "content")}
    if isinstance(slots, dict):
        natives.update(
            slot["native"]
            for slot in slots.values()
            if isinstance(slot, dict) and isinstance(slot.get("native"), str)
        )
    if injected in natives or injected in props:
        _die(f"{where}: 'native' repeats another parameter")
    observations = interaction.get("observations")
    if not isinstance(observations, dict) or not observations:
        _die(f"{where}: 'observations' must be a non-empty object")
    for kind, observed in sorted(observations.items()):
        if kind not in INTERACTION_KINDS:
            _die(
                f"{where}: unknown observation {kind!r}; vocabulary: "
                + ", ".join(sorted(INTERACTION_KINDS))
            )
        prop = props.get(observed) if isinstance(observed, str) else None
        if prop is None:
            _die(f"{where}: observation {kind!r} must name one of the props")
        if prop.get("type") != "actionId":
            _die(f"{where}: prop {observed!r} must be an actionId")
        _validate_reported_payload(where, observed, prop)


def _validate_reported_payload(
    where: str, prop_name: object, prop: dict[str, Any]
) -> None:
    """Check a host-reported prop carries exactly one boolean payload field.

    The host fills one named boolean; more fields would mean the host guessed
    which one reports the value, which is what the planner refuses to do
    everywhere else.

    Args:
        where: Where the prop was declared, for error messages.
        prop_name: The prop's schema name.
        prop: The prop's schema entry.
    """
    payload = prop.get("payload")
    field = payload[0] if isinstance(payload, list) and len(payload) == 1 else None
    if (
        not isinstance(field, dict)
        or field.get("type") != "boolean"
        or not isinstance(field.get("name"), str)
        or REPORTED_FIELD.fullmatch(field["name"]) is None
    ):
        _die(f"{where}: prop {prop_name!r} needs one boolean payload field")


def _claimed_parameter(where: str, key: str, value: object, claimed: set[str]) -> str:
    """Return one declared native parameter after checking what it claims.

    The state names native parameters the generated call must fill itself, so
    each one has to be a parameter name, and none may be a parameter the
    component's other declarations already name: two arguments for one parameter
    would not compile, and a shadowed prop would never reach the component.

    Args:
        where: Prefix for error messages.
        key: The state key naming the parameter, for the message.
        value: The raw value, which must be a parameter name.
        claimed: Parameters the declaration already names.

    Returns:
        The parameter name.
    """
    if not isinstance(value, str) or NATIVE_PARAMETER.match(value) is None:
        _die(f"{where}: {key!r} must be a parameter name")
    if value in claimed:
        _die(f"{where}: {key!r} repeats another parameter")
    return value


def _validate_state(
    name: str,
    props: dict[str, Any],
    children: dict[str, Any],
    slots: object,
    state: object,
) -> None:
    """Check a component's declared state holder against the vocabulary.

    The state object is the host's, not the app's: the schema names the native
    parameter it fills, the family whose create/drive/report logic applies, the
    prop carrying Python's desired value, and the prop reporting settled
    changes. The generator omits both props from the app's native arguments,
    exactly as it does for an observed interaction.

    A family may also name a native parameter it *completes* rather than fills
    from a prop: ``dismiss`` is the callback through which the component
    announces a dismissal it has already carried out, which the props above
    already report, so the host answers it with an empty callback.

    Args:
        name: Component name, for error messages.
        props: The component's props; the value and report must be among them.
        children: The component's ``children`` object, whose native parameter
            the state holder must not reuse.
        slots: The component's declared slots, which claim their own natives.
        state: The raw ``state`` object, or None.
    """
    if state is None:
        return
    where = f"component {name!r} state"
    if not isinstance(state, dict):
        _die(f"{where} must be an object")
    unknown = sorted(set(state) - STATE_KEYS)
    if unknown:
        _die(f"{where} has unknown keys: {', '.join(unknown)}")
    natives = {children.get("native", "content")}
    if isinstance(slots, dict):
        natives.update(
            slot["native"]
            for slot in slots.values()
            if isinstance(slot, dict) and isinstance(slot.get("native"), str)
        )
    claimed = natives | set(props)
    injected = _claimed_parameter(where, "native", state.get("native"), claimed)
    kind = state.get("kind")
    if not isinstance(kind, str) or kind not in STATE_KINDS:
        _die(
            f"{where}: unknown state kind {kind!r}; vocabulary: "
            + ", ".join(sorted(STATE_KINDS))
        )
    value = state.get("value")
    prop = props.get(value) if isinstance(value, str) else None
    if prop is None:
        _die(f"{where}: 'value' must name one of the props")
    if prop.get("type") != "boolean":
        # The family drives one boolean -- a drawer is open or it is not -- so
        # a prop of any other type cannot carry that family's desired state.
        _die(f"{where}: prop {value!r} must be a boolean")
    report = state.get("report")
    reported = props.get(report) if isinstance(report, str) else None
    if reported is None:
        _die(f"{where}: 'report' must name one of the props")
    if reported.get("type") != "actionId":
        _die(f"{where}: prop {report!r} must be an actionId")
    _validate_reported_payload(where, report, reported)
    dismiss = state.get("dismiss")
    if dismiss is not None:
        _claimed_parameter(where, "dismiss", dismiss, claimed | {injected})


def _validate_slots(
    name: str,
    props: dict[str, Any],
    children: dict[str, Any],
    slots: object,
) -> None:
    """Check a component's declared slots against the slot vocabulary.

    Args:
        name: Component name, for error messages.
        props: The component's props, which no slot may shadow.
        children: The component's ``children`` object, whose native parameter a
            slot must not reuse either.
        slots: The raw ``slots`` object.
    """
    if not isinstance(slots, dict):
        _die(f"component {name!r} needs a 'slots' object")
    natives: set[str] = {children.get("native", "content")}
    for slot_name, slot in sorted(slots.items()):
        where = f"component {name!r} slot {slot_name!r}"
        _validate_slot(where, slot_name, slot, natives, props)


def _validate_slot(
    where: str,
    slot_name: str,
    slot: object,
    natives: set[str],
    props: dict[str, Any],
) -> None:
    """Check one declared slot, claiming its native parameter in ``natives``.

    Args:
        where: Human-readable location, for error messages.
        slot_name: The declared ``camelCase`` name.
        slot: The raw slot object.
        natives: Native parameters the component already claims, including the
            primary children's.
        props: The component's props, which no argument name may repeat.
    """
    if not isinstance(slot_name, str) or not SLOT_NAME.match(slot_name):
        _die(f"{where}: the name must be camelCase")
    if slot_name in RESERVED_SLOTS or slot_name in props:
        _die(f"{where}: the name collides with a prop or reserved argument")
    if not isinstance(slot, dict):
        _die(f"{where} must be an object")
    unknown = sorted(set(slot) - SLOT_KEYS)
    if unknown:
        _die(f"{where} has unknown keys: {', '.join(unknown)}")
    native = slot.get("native")
    if not isinstance(native, str) or not NATIVE_PARAMETER.match(native):
        _die(f"{where}: 'native' must be a parameter name")
    if native in natives or native in props:
        # Two arguments with one name is not valid Kotlin, and a slot that
        # shadows a prop drops one of them silently.
        _die(f"{where}: 'native' repeats another parameter")
    natives.add(native)
    if not isinstance(slot.get("nullable", False), bool):
        _die(f"{where}: 'nullable' must be a boolean")
    if slot.get("kind", "content") not in SLOT_KINDS:
        _die(f"{where}: 'kind' must be one of " + ", ".join(sorted(SLOT_KINDS)))
    if slot.get("consume") not in {None, *CONSUMERS}:
        _die(f"{where}: 'consume' must be one of " + ", ".join(sorted(CONSUMERS)))
    if slot.get("nullable", False) and slot.get("consume") is not None:
        # A consumed scope has to be applied, which a null slot never is.
        _die(f"{where}: 'consume' needs a non-nullable slot")
    if slot.get("nullable", False) and slot.get("kind") == "items":
        # A nullable parameter takes a plain lambda, which cannot list items
        # lazily; composing them eagerly instead would be a different tree.
        _die(f"{where}: an items slot cannot be nullable")


def _validate_prop(name: str, prop_name: str, prop: dict[str, Any]) -> None:
    if not isinstance(prop, dict):
        _die(f"prop {name}.{prop_name} must be an object")
    ptype = prop.get("type")
    if ptype not in PROP_TYPE_VOCABULARY:
        _die(
            f"prop {name}.{prop_name} has unknown type {ptype!r}; "
            f"vocabulary: {sorted(PROP_TYPE_VOCABULARY)}"
        )
    if ptype == "enum":
        values = prop.get("values")
        if (
            not isinstance(values, list)
            or not values
            or not all(isinstance(value, str) for value in values)
        ):
            _die(f"enum prop {name}.{prop_name} needs a non-empty string 'values' list")
    if "required" in prop and not isinstance(prop["required"], bool):
        _die(f"prop {name}.{prop_name} 'required' must be a boolean")
    for bound in ("minimum", "maximum"):
        if bound in prop and (
            not isinstance(prop[bound], int | float)
            or isinstance(prop[bound], bool)
            or (isinstance(prop[bound], float) and not math.isfinite(prop[bound]))
        ):
            _die(f"prop {name}.{prop_name} {bound} must be finite numeric data")
    if "minimum" in prop and "maximum" in prop and prop["minimum"] > prop["maximum"]:
        _die(f"prop {name}.{prop_name} minimum exceeds maximum")
    if "fallback" in prop:
        if prop.get("decode") is None:
            _die(f"prop {name}.{prop_name} 'fallback' needs a 'decode'")
        if not isinstance(prop["fallback"], str) or not prop["fallback"]:
            _die(f"prop {name}.{prop_name} 'fallback' must be Kotlin source")
    _validate_defaults(name, prop_name, prop, ptype)
    if "provider" in prop:
        _validate_provider(name, prop_name, prop)
    _validate_nullable(name, prop_name, prop)


def _validate_defaults(
    name: str,
    prop_name: str,
    prop: dict[str, Any],
    ptype: object,
) -> None:
    """Check a prop's native default and the fallback a dp prop must declare.

    Args:
        name: Component name, for error messages.
        prop_name: Prop name, for error messages.
        prop: The prop's raw entry.
        ptype: The prop's declared type.
    """
    if "nativeDefault" in prop:
        if not isinstance(prop["nativeDefault"], str) or not prop["nativeDefault"]:
            _die(f"prop {name}.{prop_name} 'nativeDefault' must be Kotlin source")
        if ptype not in {"value", "dp"}:
            # Anything else that carried one would never be read, and the
            # stated default would quietly differ from the pinned one.
            _die(
                f"prop {name}.{prop_name} 'nativeDefault' is read only for "
                "value and dp props"
            )
    if ptype == "dp" and not (
        prop.get("required") or "default" in prop or "nativeDefault" in prop
    ):
        _die(
            f"prop {name}.{prop_name} dp props must be required or carry a "
            "'default' or 'nativeDefault'"
        )


def _validate_nullable(name: str, prop_name: str, prop: dict[str, Any]) -> None:
    """Check which of the two nullable shapes a prop may have.

    They are not the same shape. A *required* nullable prop has no omission: the
    pinned parameter takes no default, so the value is passed through as it
    stands, and that only lines up when the wire type *is* the native type -- an
    undecoded scalar, where ``None`` is a ``null``. An *optional* nullable prop
    is the ``OptionalValue`` form, where absence and an explicit null are two
    facts, and the generated adapter implements that for a value family
    (``Button.elevation``). Every other combination would either be passed where
    it does not fit or dropped silently, so it is refused here.

    Args:
        name: Component name, for error messages.
        prop_name: The prop's schema name.
        prop: Its raw schema entry.
    """
    if not prop.get("nullable"):
        return
    from pycompose.schema.codegen.adapters import SCALAR_KOTLIN

    if prop.get("required"):
        if prop["type"] not in SCALAR_KOTLIN or "decode" in prop:
            _die(
                f"prop {name}.{prop_name}: a required nullable prop is passed "
                "through, so it must be an undecoded scalar"
            )
    elif prop["type"] != "value":
        _die(
            f"prop {name}.{prop_name}: an optional nullable prop needs the "
            "value family's absent/null distinction"
        )


def _validate_provider(name: str, prop_name: str, prop: dict[str, Any]) -> None:
    """Check a prop delivered through a zero-arg native lambda.

    A provider prop states a value the host reads during composition; the native
    parameter is a function the host supplies, never one the app can name. The
    prop stays required because an absent value would need a call-site branch
    between two overload shapes, which the plan rejects (ADR-0016 decision 22).
    ``returns`` is the pinned lambda's return type: the generator needs it to
    coerce the wire value, and check_upstream.py re-derives it from the pin.

    Args:
        name: Component name, for error messages.
        prop_name: The prop's schema name.
        prop: Its raw schema entry, whose ``provider`` object is validated.
    """
    provider = prop["provider"]
    if not isinstance(provider, dict):
        _die(f"prop {name}.{prop_name} 'provider' must be an object")
    unknown = sorted(set(provider) - PROVIDER_KEYS)
    if unknown:
        _die(
            f"prop {name}.{prop_name} provider has unknown keys: " + ", ".join(unknown)
        )
    injected = provider.get("native")
    if not isinstance(injected, str) or NATIVE_PARAMETER.fullmatch(injected) is None:
        _die(f"prop {name}.{prop_name} provider 'native' must be a parameter name")
    returns = provider.get("returns")
    if not isinstance(returns, str) or DOTTED_NAME.fullmatch(returns) is None:
        _die(f"prop {name}.{prop_name} provider 'returns' must be a Kotlin type name")
    if not prop.get("required"):
        _die(f"prop {name}.{prop_name} provider 'native' needs the prop to be required")
    if prop.get("nullable"):
        _die(f"prop {name}.{prop_name} provider cannot come from a nullable prop")
    if prop.get("type") in {"modifier", "actionId"}:
        _die(f"prop {name}.{prop_name} provider cannot wrap a {prop['type']} prop")


def _validate_action(action_id: str, action: dict[str, Any]) -> None:
    if not isinstance(action, dict):
        _die(f"action {action_id!r} must be an object")
    payload = action.get("payload", {})
    if not isinstance(payload, dict):
        _die(f"action {action_id!r} 'payload' must be an object")
    for field_name, field in sorted(payload.items()):
        is_invalid = (
            not isinstance(field, dict) or field.get("type") not in PROP_TYPE_VOCABULARY
        )
        if is_invalid:
            _die(
                f"action {action_id!r} payload field {field_name!r} has an invalid type"
            )
        _validate_prop(action_id, field_name, field)


def render_payloads(registry: dict[str, Any]) -> str:
    """Generate Python input payload contracts from registry action fields."""
    actions = registry["actions"]
    names = {
        action_id: "".join(
            part[:1].upper() + part[1:]
            for part in re.findall(r"[A-Za-z0-9]+", action_id)
        )
        + "Payload"
        for action_id in sorted(actions)
    }
    if len(set(names.values())) != len(names) or any(
        not name.isidentifier() for name in names.values()
    ):
        _die("action ids must produce unique Python payload names")
    imports = {"TypedDict"}
    declarations = []
    simple_types = {
        "string": "str",
        "color": "str",
        "resource": "str",
        "actionId": "str",
        "boolean": "bool",
        "integer": "int",
        "durationMs": "int",
        "number": "int | float",
        "dp": "int | float",
        "modifier": "dict[str, JsonValue]",
    }
    uses_json = False
    for action_id, name in names.items():
        fields = {}
        for field_name, prop in sorted(actions[action_id].get("payload", {}).items()):
            if prop["type"] == "enum":
                imports.add("Literal")
                annotation = (
                    "Literal["
                    + ", ".join(json.dumps(value) for value in sorted(prop["values"]))
                    + "]"
                )
            else:
                annotation = simple_types[prop["type"]]
            uses_json |= prop["type"] == "modifier"
            if not prop.get("required", False):
                imports.add("NotRequired")
                annotation = f"NotRequired[{annotation}]"
            fields[field_name] = annotation
        payload = actions[action_id].get("payload", {})
        if all(
            field.isidentifier() and not keyword.iskeyword(field) for field in payload
        ):
            body = "\n".join(
                f"    {field}: {annotation}" for field, annotation in fields.items()
            )
            declarations.append(f"class {name}(TypedDict):\n" + (body or "    pass"))
        else:
            declarations.append(
                f'{name} = TypedDict(\n    "{name}",\n    {{\n'
                + "\n".join(
                    f"        {json.dumps(field)}: {annotation},"
                    for field, annotation in fields.items()
                )
                + "\n    },\n)"
            )
    return (
        f"# {GENERATED_NOTICE}\n"
        '"""Generated host action input payload contracts."""\n\n'
        "from __future__ import annotations\n\n"
        f"from typing import {', '.join(sorted(imports))}\n"
        + ("\nfrom pycompose.core.props import JsonValue\n" if uses_json else "")
        + "\n__all__ = [\n"
        + "".join(f'    "{name}",\n' for name in sorted(names.values()))
        + "]\n\n\n"
        + "\n\n\n".join(declarations)
        + "\n"
    )


def render_ir_schema(registry: dict[str, Any]) -> str:
    """Render the derived JSON Schema for canonical IR snapshots."""
    from pycompose.schema.codegen.values import json_definitions

    components = registry["components"]
    action_ids = sorted(registry.get("actions", {}))
    component_defs = {
        f"C_{name}": _component_schema(name, comp, action_ids)
        for name, comp in sorted(components.items())
    }
    ir_schema: dict[str, Any] = {
        "$schema": JSON_SCHEMA_DRAFT,
        "$id": "https://pycompose.dev/schema/ir.schema.json",
        "title": "PyCompose IR: canonical snapshot",
        "type": "object",
        "required": ["version", "schemaVersion", "root"],
        "properties": {
            "version": {"type": "string"},
            "schemaVersion": {"enum": _supported(registry)},
            "root": {"$ref": "#/definitions/Node"},
        },
        "definitions": {
            "Node": _node_schema(sorted(component_defs)),
            "ModifierOperation": _modifier_schema(registry, action_ids),
            **component_defs,
            **json_definitions(registry),
        },
    }
    # Each supported envelope selects its own recursive catalog from the manifest.
    branches = []
    for version in _supported(registry):
        prefix = "V_" + version.replace(".", "_") + "_"
        ir_schema["definitions"][prefix + "ModifierOperation"] = _modifier_schema(
            registry, action_ids, version
        )
        available = {}
        for name, spec in components.items():
            if _version_key(spec.get("since", version)) > _version_key(version):
                continue
            scoped = {
                **spec,
                "props": {
                    key: {
                        k: v
                        for k, v in prop.items()
                        if k != "valueType" or _version_key(version) >= (1, 11, 0)
                    }
                    for key, prop in spec["props"].items()
                    if _version_key(prop.get("since", version)) <= _version_key(version)
                },
            }
            schema = _component_schema(name, scoped, action_ids)
            if "modifier" in scoped["props"]:
                schema["properties"]["props"]["properties"]["modifier"]["properties"][
                    "operations"
                ]["items"] = {"$ref": "#/definitions/" + prefix + "ModifierOperation"}
            available[prefix + name] = schema
        node_name = prefix + "Node"
        node_schema = _node_schema(sorted(available))
        node_schema["properties"]["children"]["items"] = {
            "$ref": "#/definitions/" + node_name
        }
        ir_schema["definitions"].update(available)
        ir_schema["definitions"][node_name] = node_schema
        branches.append(
            {
                "if": {"properties": {"schemaVersion": {"const": version}}},
                "then": {
                    "properties": {"root": {"$ref": "#/definitions/" + node_name}}
                },
            }
        )
    ir_schema["allOf"] = branches
    return json.dumps(ir_schema, indent=2, sort_keys=True) + "\n"


def _modifier_schema(
    registry: dict[str, Any], actions: list[str], version: str | None = None
) -> dict[str, Any]:
    variants: list[Any] = []
    for name, modifier in sorted(registry.get("modifiers", {}).items()):
        props = modifier["props"]
        if version is not None and any(
            _version_key(p.get("since", version)) > _version_key(version)
            for p in props.values()
        ):
            continue
        scoped = {
            key: {
                k: v
                for k, v in prop.items()
                if k != "valueType"
                or version is None
                or _version_key(version) >= (1, 11, 0)
            }
            for key, prop in props.items()
        }
        variants.append(
            {
                "type": "object",
                "additionalProperties": False,
                "required": [
                    "type",
                    *sorted(k for k, p in props.items() if p.get("required")),
                ],
                "properties": {
                    "type": {"const": name},
                    **{k: _prop_schema(p, actions) for k, p in scoped.items()},
                },
            }
        )
    return {"anyOf": variants or [False]}


def _node_schema(component_refs: list[str]) -> dict[str, Any]:
    return {
        "type": "object",
        "required": ["id", "type", "props"],
        "properties": {
            "id": {"type": "string", "minLength": 1},
            "type": {"type": "string"},
            "props": {"type": "object"},
            "slot": {"type": "string", "pattern": SLOT_NAME.pattern},
            "children": {
                "type": "array",
                "items": {"$ref": "#/definitions/Node"},
            },
        },
        "allOf": [
            {"anyOf": [{"$ref": f"#/definitions/{ref}"} for ref in component_refs]}
        ],
    }


def _component_schema(
    name: str, comp: dict[str, Any], action_ids: list[str]
) -> dict[str, Any]:
    props = sorted(comp["props"].items())
    props_schema = {
        "type": "object",
        "properties": {
            prop_name: _prop_schema(prop, action_ids) for prop_name, prop in props
        },
        "additionalProperties": False,
    }
    required = [prop_name for prop_name, prop in props if prop.get("required")]
    if required:
        props_schema["required"] = required

    node_properties: dict[str, object] = {
        "type": {"const": name},
        "props": props_schema,
    }
    children = comp.get("children", {})
    slots = sorted(comp.get("slots", {}))
    if children.get("allowed") or slots:
        child: dict[str, Any] = {}
        if slots:
            child["properties"] = {"slot": {"enum": slots}}
            if not children.get("allowed"):
                child["required"] = ["slot"]
        elif not children.get("allowed"):
            child["properties"] = {"slot": False}
        minimum = children.get("min", 0)
        if minimum and not slots:
            child["minItems"] = minimum
        node_properties["children"] = {"type": "array", "items": child}
    else:
        node_properties["children"] = False
    return {"type": "object", "properties": node_properties}


def _prop_schema(prop: dict[str, Any], action_ids: list[str]) -> dict[str, Any]:
    from pycompose.schema.codegen.values import parameter_schema

    ptype = prop["type"]
    basic = {
        "string": "string",
        "color": "string",
        "integer": "integer",
        "durationMs": "integer",
        "number": "number",
        "dp": "number",
        "boolean": "boolean",
        "value": "object",
    }
    if ptype in basic:
        value: dict[str, Any] = (
            parameter_schema({"type": "float"})
            if ptype == "dp"
            else {"type": basic[ptype]}
        )
    elif ptype == "resource":
        native = "|".join(kind for kind in prop["values"] if kind != "asset")
        patterns = []
        if native:
            patterns.append(f"@({native})/[a-z][a-z0-9_]*")
        if "asset" in prop["values"]:
            patterns.append(
                r"@asset/[A-Za-z0-9_-][A-Za-z0-9_.-]*(?:/[A-Za-z0-9_-][A-Za-z0-9_.-]*)*"
            )
        value = {
            "type": "string",
            "pattern": "^(" + "|".join(patterns) + r")(?![\s\S])",
        }
    elif ptype == "enum":
        value = {"enum": sorted(prop["values"])}
    elif ptype == "actionId":
        value = {"enum": action_ids}
    elif ptype == "modifier":
        value = {
            "type": "object",
            "properties": {
                "operations": {
                    "type": "array",
                    "items": {"$ref": "#/definitions/ModifierOperation"},
                }
            },
        }
    else:
        _die(f"unsupported prop type {ptype!r}")
    if "default" in prop:
        value["default"] = prop["default"]
    for bound in ("minimum", "maximum"):
        if bound in prop:
            value[bound] = prop[bound]
    if "valueType" in prop:
        tagged = parameter_schema({**prop, "type": "value", "nullable": False})
        value = tagged if ptype == "value" else {"anyOf": [value, tagged]}
    return {"anyOf": [value, {"type": "null"}]} if prop.get("nullable") else value


def render_validators(registry: dict[str, Any]) -> str:
    """Render typed runtime tables directly from the SSOT registry."""
    action_ids = sorted(registry.get("actions", {}))
    ids = [json.dumps(action_id) for action_id in action_ids]
    if len(ids) == 1:
        action_tuple = f"({ids[0]},)"
    elif ids:
        action_tuple = "(" + ", ".join(ids) + ")"
    else:
        action_tuple = "()"
    raw = json.dumps(registry, sort_keys=True, separators=(",", ":"))
    # Adjacent literals embed the entire registry without a runtime file read.
    chunks = [
        _python_string(raw[index : index + 50]) for index in range(0, len(raw), 50)
    ]
    literals = "\n".join(f"        {chunk}" for chunk in chunks)
    minimum_schema = min(_supported(registry), key=_version_key)
    body = (
        f"# {GENERATED_NOTICE}\n"
        '"""Generated component, prop, children and action validation tables."""\n\n'
        "from __future__ import annotations\n\n"
        "import json\n\n"
        "from pycompose.core.registry_types import Registry\n\n"
        '__all__ = [\n    "KNOWN_ACTION_IDS",\n    "MIN_LIBRARY_VERSION",\n'
        '    "MIN_SCHEMA_VERSION",\n    "REGISTRY",\n    "SCHEMA_VERSION",\n]\n\n'
        f"SCHEMA_VERSION: str = {json.dumps(registry['schemaVersion'])}\n"
        f"MIN_SCHEMA_VERSION: str = {json.dumps(minimum_schema)}\n"
        f"MIN_LIBRARY_VERSION: str = {json.dumps(registry['minLibraryVersion'])}\n"
        f"KNOWN_ACTION_IDS: tuple[str, ...] = {action_tuple}\n"
        f"REGISTRY: Registry = Registry.from_mapping(\n    json.loads(\n{literals}\n"
        "    )\n)\n"
    )
    return body


def _python_string(value: str) -> str:
    # Choose quotes that preserve embedded JSON without unnecessary escaping.
    if '"' in value and "'" not in value:
        escaped = json.dumps(value)[1:-1].replace('\\"', '"')
        return f"'{escaped}'"
    return json.dumps(value)


def _read(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8")
    except OSError:
        return None


def _kt_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False).replace("$", "\\$")


def _python_prop(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def _python_type(component: str, name: str, prop: dict[str, Any]) -> str:
    if "valueType" in prop:
        return "JsonValue"
    if prop["type"] == "enum":
        return f"_{component}{name[:1].upper() + name[1:]}"
    return {
        "string": "str",
        "color": "str",
        "resource": "str",
        "actionId": "str",
        "boolean": "bool",
        "integer": "int",
        "durationMs": "int",
        "number": "int | float",
        "dp": "int | float",
        "modifier": "Modifier",
    }[prop["type"]]


def _python_class_docstring(name: str) -> list[str]:
    """Render the generated class docstring, wrapped when the name is long.

    Args:
        name: The generated class name.

    Returns:
        The docstring's source lines.
    """
    summary = f"Native {name}; props and defaults follow the component manifest."
    if len(f'    """{summary}"""') <= 88:
        return [f'    """{summary}"""']
    return [
        f'    """Native {name};',
        '    props and defaults follow the component manifest."""',
    ]


def _python_constructor(name: str, spec: dict[str, Any]) -> list[str]:
    props = spec["props"]
    alias = spec["children"].get("kind")
    lines = [
        f"class {name}(Component):",
        *_python_class_docstring(name),
        "",
        "    __slots__ = ()",
        f'    component_type = "{name}"',
        "",
        "    def __init__(",
        "        self,",
        "        *,",
        "        id: str,",
    ]
    signature, arguments = _python_signature(name, spec)
    lines.extend(signature)
    lines.extend(
        [
            "    ) -> None:",
            f'        """Construct a registered {name}.',
            "",
            "        Args:",
            *(
                f"            {field}: {description}"
                for field, description in arguments.items()
            ),
        ]
    )
    if spec["children"]["allowed"] and alias in {"content", "items"}:
        lines.extend(
            [
                "",
                "        Raises:",
                "            IrValidationError: If slot and children are both set.",
            ]
        )
    lines.extend(['        """', "        props: dict[str, JsonValue] = {}"])
    for field, prop in sorted(props.items()):
        python_name = _python_prop(field)
        if field == "modifier":
            continue
        if not prop.get("required", False):
            absent = "UNSET" if prop.get("nullable") else "None"
            condition = (
                f"not isinstance({python_name}, _Unset)"
                if prop.get("nullable")
                else f"{python_name} is not {absent}"
            )
            lines.extend(
                [
                    f"        if {condition}:",
                    f'            props["{python_name}"] = {python_name}',
                ]
            )
        else:
            lines.append(f'        props["{python_name}"] = {python_name}')
    if spec["children"]["allowed"] and alias in {"content", "items"}:
        lines.extend(
            [
                f"        if {alias} is not None:",
                "            if children:",
                "                raise IrValidationError(",
                '                    "cannot supply both slot and children", '
                "node_id=id",
                "                )",
                f'            children = content_nodes({alias}, key="{alias}")',
            ]
        )
    children = "()"
    if spec["children"]["allowed"]:
        lines.append('        normalized = content_nodes(children, key="children")')
        children = "normalized"
    slot_lines, children = _python_slot_body(spec, children)
    lines.extend(slot_lines)
    modifier = ", modifier=modifier" if "modifier" in props else ""
    invocation = f"id=id, children={children}{modifier}, **props"
    if len(invocation) + len("        super().__init__()") > 88:
        lines.extend(
            ["        super().__init__(", f"            {invocation}", "        )"]
        )
    else:
        lines.append(f"        super().__init__({invocation})")
    return [*lines, "", ""]


def _python_signature(
    name: str, spec: dict[str, Any]
) -> tuple[list[str], dict[str, str]]:
    """Render one component's keyword parameters and their docstring lines.

    Args:
        name: Component name, for prop annotations.
        spec: The component's manifest entry.

    Returns:
        Signature lines, then one description per parameter.
    """
    lines: list[str] = []
    arguments = {"id": "Stable instance key."}
    for field, prop in sorted(spec["props"].items()):
        python_name = _python_prop(field)
        annotation, description = _python_argument(name, field, prop)
        lines.append(f"        {python_name}: {annotation},")
        arguments[python_name] = description
    alias = spec["children"].get("kind")
    if spec["children"]["allowed"]:
        lines.append("        children: Content = (),")
        arguments["children"] = "Ordered child nodes with stable keys."
        if alias in {"content", "items"}:
            lines.append(f"        {alias}: Content | None = None,")
            arguments[alias] = f"Alternative spelling for {alias} children."
    for slot_name, slot in sorted(spec.get("slots", {}).items()):
        slot_arg = _python_prop(slot_name)
        lines.append(f"        {slot_arg}: Content | None = None,")
        arguments[slot_arg] = f"Nodes for the native {slot['native']} slot."
    return lines, arguments


def _python_slot_body(spec: dict[str, Any], children: str) -> tuple[list[str], str]:
    """Render the statements that collect one component's named slots.

    Args:
        spec: The component's manifest entry.
        children: Expression for the primary children so far.

    Returns:
        Body lines, then the child expression the constructor passes on.
    """
    if not spec.get("slots"):
        return [], children
    lines = ["        slotted: tuple[Node, ...] = ()"]
    for slot_name, _slot in sorted(spec["slots"].items()):
        slot_arg = _python_prop(slot_name)
        call = f"slotted += slot_nodes({slot_arg}, "
        lines.append(f"        if {slot_arg} is not None:")
        single = f'{call}key="{slot_name}", slot="{slot_name}")'
        if len(single) + len("            ") <= 88:
            lines.append(f"            {single}")
            continue
        lines.extend(
            [
                "            slotted += slot_nodes(",
                f"                {slot_arg},",
                f'                key="{slot_name}",',
                f'                slot="{slot_name}",',
                "            )",
            ]
        )
    combined = "slotted" if children == "()" else "normalized + slotted"
    return lines, combined


def _python_argument(
    component: str, field: str, prop: dict[str, Any]
) -> tuple[str, str]:
    annotation = _python_type(component, field, prop)
    if prop.get("nullable"):
        annotation += " | None"
    if prop.get("required"):
        return annotation, f"Required native {field}."
    if prop.get("nullable"):
        return (
            annotation + " | _Unset = UNSET",
            f"Native {field}; omitted uses its default; None is null.",
        )
    return annotation + " | None = None", f"Native {field}; None uses its default."


def render_python_components(
    registry: dict[str, Any], package: str = "pycompose.m3"
) -> str:
    """Generate typed Python constructors from the native manifest.

    Args:
        registry: The parsed schema.
        package: The package these are imported from, named in the module
            docstring so an app slice does not point readers at the catalog.

    Returns:
        The generated module.
    """
    names = sorted(registry["components"])
    lines = [
        f"# {GENERATED_NOTICE}",
        f'"""Typed native component constructors; import from {package}."""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Literal",
        "",
        "from pycompose.components.base import Component",
        "from pycompose.components.modifiers import Modifier",
        "from pycompose.composition import Content, content_nodes, slot_nodes",
        "from pycompose.core.node import Node",
        "from pycompose.core.props import JsonValue",
        "from pycompose.errors import IrValidationError",
        "",
        "__all__ = [",
        *(f'    "{name}",' for name in names),
        "]",
        "",
        "",
    ]
    if any(
        p.get("nullable")
        for s in registry["components"].values()
        for p in s["props"].values()
    ):
        index = lines.index("from pycompose.errors import IrValidationError")
        lines.insert(index, "from pycompose.core.values import UNSET, _Unset")
    for name, spec in sorted(registry["components"].items()):
        for field, prop in sorted(spec["props"].items()):
            if prop["type"] == "enum" and "valueType" not in prop:
                lines.extend(
                    [
                        f"{_python_type(name, field, prop)} = Literal[",
                        *(f"    {json.dumps(value)}," for value in prop["values"]),
                        "]",
                        "",
                    ]
                )
    lines.append("")
    for name, spec in sorted(registry["components"].items()):
        lines.extend(_python_constructor(name, spec))
    return "\n".join(lines).rstrip() + "\n"


def render_python_exports(
    registry: dict[str, Any], package: str = "pycompose.m3"
) -> str:
    """Generate the import surface for all supported native components.

    Args:
        registry: The parsed schema.
        package: The package the constructors live in. The library ships the
            full catalog under ``pycompose.m3``; a per-app slice (ADR-0014)
            ships its own subset under a bare ``m3``, because importing the
            library's full set would bring back every component the app just
            declined to ship.

    Returns:
        The generated ``__init__.py``.
    """
    names = sorted(registry["components"])
    # Sorted by module, because the pre-commit isort hook would otherwise
    # reorder a file nobody may hand-edit and `gen.py --check` would then fail
    # forever on it -- the same two-gates-revert-each-other trap as ktlint
    # against the Kotlin adapters. "pycompose.m3.generated_components" sorts
    # after "pycompose.components.modifiers"; a bare "m3" sorts before it, so
    # the order genuinely differs between the library and an app slice.
    imports = [
        (f"{package}.generated_components", names),
        ("pycompose.components.modifiers", ["Modifier"]),
    ]
    blocks = [
        f"from {module} import ("
        + "".join(f"\n    {name}," for name in entries)
        + "\n)"
        for module, entries in sorted(imports, key=lambda item: item[0])
    ]
    return "\n".join(
        [
            f"# {GENERATED_NOTICE}",
            '"""Native components backed by the shared manifest."""',
            "",
            *blocks,
            "",
            "__all__ = [",
            *(f'    "{name}",' for name in sorted([*names, "Modifier"])),
            "]",
            "",
        ]
    )


def _kt_field(name: str) -> str:
    if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) is None:
        _die(f"invalid Kotlin contract identifier: {name!r}")
    return f"`{name}`"


def _kt_type(prop: dict[str, Any]) -> str:
    if prop.get("nullable") and not prop.get("required"):
        return "OptionalValue"
    suffix = "?" if prop.get("nullable") else ""
    if "valueType" in prop:
        return "JsonElement" + suffix
    return {
        "string": "String",
        "color": "String",
        "resource": "String",
        "actionId": "String",
        "enum": "String",
        "boolean": "Boolean",
        "integer": "Long",
        "durationMs": "Long",
        "number": "Double",
        "dp": "Double",
        "modifier": "JsonObject",
    }[prop["type"]] + suffix


def _kt_default(prop: dict[str, Any]) -> str:
    if prop.get("nullable"):
        return "" if prop.get("required") else " = OptionalValue.Absent"
    if "default" not in prop:
        return "" if prop.get("required", False) else " = null"
    value = prop["default"]
    if "valueType" in prop:
        return f" = JsonPrimitive({_kt_string(value)})"
    if isinstance(value, str | bool):
        return " = " + (
            _kt_string(value) if isinstance(value, str) else str(value).lower()
        )
    if prop["type"] in {"integer", "durationMs"}:
        return f" = {value}L"
    if prop["type"] in {"number", "dp"}:
        return f" = {float(value)}"
    _die("unsupported Kotlin prop default")


def _kt_props(name: str, props: dict[str, Any], base: str = "UiProps") -> list[str]:
    lines = ["@Serializable"]
    if not props:
        return [*lines, f"data object {name} : {base}", ""]
    lines.append(f"data class {name}(")
    for field, prop in sorted(props.items()):
        nullable = (
            "?"
            if not prop.get("nullable")
            and not prop.get("required", False)
            and "default" not in prop
            else ""
        )
        override = "override " if field == "modifier" and base == "UiProps" else ""
        lines.append(
            f"    {override}val {_kt_field(field)}: "
            f"{_kt_type(prop)}{nullable}{_kt_default(prop)},"
        )
    return [*lines, f") : {base}", ""]


def render_generated_adapters(registry: dict[str, Any]) -> str:
    """Emit every Kotlin adapter the schema derives, or nothing when none does.

    Args:
        registry: The parsed schema.

    Returns:
        The generated Kotlin source.
    """
    from pycompose.schema.codegen.adapters import render_file

    return render_file(registry)


def render_kotlin_models(registry: dict[str, Any]) -> str:
    """Generate sealed per-component models without Android types or reflection."""
    lines = [
        f"// {GENERATED_NOTICE}",
        "package com.pycompose.ir.generated",
        "",
        "import kotlinx.serialization.SerialName",
        "import kotlinx.serialization.Serializable",
        "import kotlinx.serialization.json.JsonObject",
        "import kotlinx.serialization.json.JsonElement",
        "import kotlinx.serialization.json.JsonPrimitive",
        "import com.pycompose.ir.OptionalValue",
        "",
        "@Serializable",
        "sealed interface UiNode {",
        "    val id: String",
        "    val props: UiProps",
        "    val children: List<UiNode>",
        "    val componentType: String",
        "",
        "    /** Slot this node fills in its parent; null is the primary slot. */",
        "    val slot: String? get() = null",
        "}",
        "",
        "sealed interface UiProps {",
        "    val modifier: JsonObject? get() = null",
        "}",
        "",
        "@Serializable",
        "data class IRRoot(",
        "    val version: String,",
        "    val schemaVersion: String,",
        "    val root: UiNode,",
        "    val metadata: JsonObject? = null,",
        ")",
        "",
    ]
    names = set(registry["components"])
    generated_names = {"UiNode", "UiProps", "IRRoot", "ActionPayload"} | {
        name + "Props" for name in names
    }
    if names & generated_names:
        _die("component names collide with generated Kotlin contract types")
    for name, spec in sorted(registry["components"].items()):
        if re.fullmatch(r"[A-Z][A-Za-z0-9_]*", name) is None:
            _die(f"component name must be PascalCase for Kotlin generation: {name!r}")
        _kt_field(name)
        lines.extend(_kt_props(name + "Props", spec["props"]))
        lines.extend(
            [
                "@Serializable",
                f"@SerialName({_kt_string(name)})",
                f"data class {name}(",
                "    override val id: String,",
                f"    override val props: {name}Props,",
            ]
        )
        if spec["children"]["allowed"] or spec.get("slots"):
            # Slot children ride the same list as primary ones, so a component
            # that declares slots carries children even when it forbids primary
            # ones -- a chip's leading icon is a child, not a prop.
            lines.append("    override val children: List<UiNode> = emptyList(),")
        lines.append("    override val slot: String? = null,")
        lines.append(") : UiNode {")
        if not spec["children"]["allowed"] and not spec.get("slots"):
            lines.append("    override val children: List<UiNode> get() = emptyList()")
        lines.extend(
            [
                f"    override val componentType: String get() = {_kt_string(name)}",
                "}",
                "",
            ]
        )
    lines.extend(["sealed interface ActionPayload", ""])
    payload_names: set[str] = set()
    for action, spec in sorted(registry["actions"].items()):
        name = (
            "".join(
                part[:1].upper() + part[1:]
                for part in re.findall(r"[A-Za-z0-9]+", action)
            )
            + "Payload"
        )
        _kt_field(name)
        if name in names | generated_names | payload_names:
            _die("action ids must produce unique Kotlin payload names")
        payload_names.add(name)
        lines.extend(_kt_props(name, spec.get("payload", {}), "ActionPayload"))
    return "\n".join(lines)


def _kt_rules(props: dict[str, Any]) -> list[str]:
    lines = []
    for name, prop in sorted(props.items()):
        args = [
            _kt_string(prop["type"]),
            f"required = {str(prop.get('required', False)).lower()}",
        ]
        if "values" in prop:
            args.append(
                "values = setOf("
                + ", ".join(_kt_string(value) for value in prop["values"])
                + ")"
            )
        if "since" in prop:
            args.append(f"since = {_kt_string(prop['since'])}")
        if "valueType" in prop:
            args.append(f"valueType = {_kt_string(prop['valueType'])}")
        if prop.get("nullable"):
            args.append("nullable = true")
        args.extend(
            f"{field} = {float(prop[field])}"
            for field in ("minimum", "maximum")
            if field in prop
        )
        lines.append(
            f"                {_kt_string(name)} to PropertyRule({', '.join(args)}),"
        )
    return lines


def render_kotlin_registry(registry: dict[str, Any]) -> str:
    """Generate validation registrations from the same registry as Python."""
    minimum_schema = min(_supported(registry), key=_version_key)
    lines = [
        f"// {GENERATED_NOTICE}",
        "package com.pycompose.ir.generated",
        "",
        "import com.pycompose.ir.ComponentRule",
        "import com.pycompose.ir.PropertyRule",
        "",
        "object IrContract {",
        "    const val SCHEMA_VERSION: String = "
        + _kt_string(registry["schemaVersion"]),
        "    const val MIN_SCHEMA_VERSION: String = " + _kt_string(minimum_schema),
        "    val supportedSchemaVersions: Set<String> = setOf("
        + ", ".join(_kt_string(value) for value in _supported(registry))
        + ")",
        "    const val MIN_LIBRARY_VERSION: String = "
        + _kt_string(registry["minLibraryVersion"]),
        "    val actionIds: Set<String> = setOf("
        + ", ".join(_kt_string(name) for name in sorted(registry["actions"]))
        + ")",
        "    val components: Map<String, ComponentRule> = mapOf(",
    ]
    for name, spec in sorted(registry["components"].items()):
        lines.extend(
            [
                f"        {_kt_string(name)} to ComponentRule(",
                "            slots = setOf("
                + ", ".join(_kt_string(slot) for slot in sorted(spec.get("slots", {})))
                + "),",
                "            childrenAllowed = "
                + str(spec["children"]["allowed"]).lower()
                + ",",
                f"            minimumChildren = {spec['children'].get('min', 0)},",
                f"            since = {_kt_string(spec.get('since', minimum_schema))},",
                "            props = mapOf(",
                *_kt_rules(spec["props"]),
                "            ),",
                "        ),",
            ]
        )
    lines.extend(
        ["    )", "    val modifiers: Map<String, Map<String, PropertyRule>> = mapOf("]
    )
    for name, spec in sorted(registry.get("modifiers", {}).items()):
        lines.extend(
            [
                f"        {_kt_string(name)} to mapOf(",
                *_kt_rules(spec["props"]),
                "        ),",
            ]
        )
    lines.extend(
        [
            "    )",
            "    val actionPayloads: Map<String, Map<String, PropertyRule>> = mapOf(",
        ]
    )
    for name, spec in sorted(registry["actions"].items()):
        lines.extend(
            [
                f"        {_kt_string(name)} to mapOf(",
                *_kt_rules(spec["payload"]),
                "        ),",
            ]
        )
    lines.extend(
        [
            "    )",
            "    val effectPayloads: Map<String, Map<String, PropertyRule>> = mapOf(",
        ]
    )
    for name, spec in sorted(registry.get("effects", {}).items()):
        lines.extend(
            [
                f"        {_kt_string(name)} to mapOf(",
                *_kt_rules(spec["payload"]),
                "        ),",
            ]
        )
    lines.extend(
        [
            "    )",
            "    val lifecyclePayloads: "
            "Map<String, Map<String, PropertyRule>> = mapOf(",
        ]
    )
    for name, spec in sorted(registry.get("lifecycle", {}).items()):
        lines.extend(
            [
                f"        {_kt_string(name)} to mapOf(",
                *_kt_rules(spec["payload"]),
                "        ),",
            ]
        )
    return "\n".join([*lines, "    )", "}", ""])


def build_app(
    python_root: Path,
    *,
    android_root: Path | None = None,
    check: bool = False,
) -> int:
    """Generate an app's component slice, or verify it (ADR-0014).

    The two roots are separate because a scaffolded project keeps them apart:
    ``pycompose init`` writes Python under ``app/`` and the Gradle project at
    the repository root, so the Kotlin slice belongs beside ``android/`` while
    the generated package belongs beside the app's own sources. The notes
    example puts both in one directory, which is why a single root looked
    sufficient until it was not.

    Args:
        python_root: Where the app's Python lives; receives the generated package.
        android_root: Where the Kotlin slice goes; defaults to ``python_root``.
        check: Report drift instead of writing.

    Returns:
        Process exit code: 0 clean, 1 on drift or an unresolvable app.
    """
    from pycompose.schema.codegen.app_slice import (
        _ADAPTERS_RELATIVE,
        _IR_RELATIVE,
        APP_PACKAGE,
        AppCodegenError,
        discover,
        discover_values,
        load_catalog,
        slice_registry,
    )

    native = python_root if android_root is None else android_root
    for root in (python_root, native):
        if not root.is_dir():
            print(f"gen.py: not a directory: {root}", file=sys.stderr)
            return 1
    try:
        registry = load_catalog(SCHEMA_PATH)
        used = discover(python_root, registry)
    except AppCodegenError as exc:
        print(f"gen.py: {exc}", file=sys.stderr)
        return 1
    if not used:
        print(
            f"gen.py: {python_root} references no components; nothing to generate",
            file=sys.stderr,
        )
        return 1

    sliced = slice_registry(
        registry, used, values=frozenset(discover_values(python_root, registry))
    )
    from pycompose.schema.codegen.values import (
        render_models,
        render_native,
        render_python,
    )

    package = APP_PACKAGE
    artifacts: dict[Path, str] = {
        python_root / package / "generated_components.py": (
            render_python_components(sliced, package)
        ),
        python_root / package / "__init__.py": render_python_exports(sliced, package),
        native / _IR_RELATIVE / "UiModels.kt": render_kotlin_models(sliced),
        native / _IR_RELATIVE / "IrContract.kt": render_kotlin_registry(sliced),
        python_root / package / "values.py": render_python(sliced),
        native / _IR_RELATIVE / "ValueModels.kt": render_models(sliced),
        native / KOTLIN_VALUES_RELATIVE: render_native(sliced),
    }
    adapters = render_generated_adapters(sliced)
    if adapters:
        artifacts[native / _ADAPTERS_RELATIVE] = adapters
    for fixture in sorted((ROOT / "pycompose/testing/fixtures").glob("*.json")):
        artifacts[native / "android/ir/src/test/resources" / fixture.name] = (
            fixture.read_text(encoding="utf-8")
        )

    if check:
        drifted = [
            str(artifact)
            for artifact, expected in artifacts.items()
            if _read(artifact) != expected
        ]
        if drifted:
            for artifact in drifted:
                print(f"gen.py: drift detected: {artifact}", file=sys.stderr)
            return 1
        print(f"gen.py: app slice up to date ({len(used)} component(s))")
        return 0

    for path, content in artifacts.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    manual = [
        name
        for name in sliced["components"]
        if sliced["components"][name].get("adapter") == "manual"
    ]
    print(
        f"gen.py: {python_root}: {len(used)} component(s) generated "
        f"({len(artifacts)} artifact(s)); "
        + (
            f"hand-written adapters still needed for {', '.join(sorted(manual))}"
            if manual
            else "no hand-written adapters needed"
        )
    )
    return 0


def _mirror_template(artifacts: dict[Path, str]) -> None:
    """Mirror every module counterpart into the template, in place.

    The template is the project ``pycompose init`` scaffolds, and it carries the
    framework sources verbatim. Whatever the modules have is what a generated app
    gets, so every counterpart is mirrored -- not just the generated half, which
    would ship a project whose renderer predates its adapters.

    A counterpart this run regenerated is copied from ``artifacts`` rather than
    read back from disk: disk still holds the previous run's output, so reading
    the file would mirror content one generation behind.

    Args:
        artifacts: The run's pending artifacts, keyed by path; template copies
            are added to it and generated copies are reused as-is.
    """
    template = ROOT / "pycompose/templates/android"
    for path in sorted(template.rglob("*")):
        if not path.is_file() or path in artifacts:
            continue
        source = ROOT / "android" / path.relative_to(template)
        if not source.is_file():
            continue
        generated = artifacts.get(source)
        if generated is not None:
            artifacts[path] = generated
            continue
        raw = source.read_bytes()
        try:
            contents = raw.decode("utf-8")
        except UnicodeDecodeError:
            contents = None
        if contents is None or "\r" in contents:
            # Not plain LF text: the Gradle wrapper jar is not source at all,
            # and gradlew.bat keeps its CRLF line endings. `pycompose init`
            # copies both, and tests/test_template_parity.py compares them byte
            # for byte -- it sees what a text artifact cannot.
            continue
        artifacts[path] = contents


def main(argv: list[str] | None = None) -> int:
    from pycompose.schema.codegen.values import render_models, render_native
    from pycompose.schema.codegen.values import render_python as render_values

    parser = argparse.ArgumentParser(
        description=(
            "Regenerate schema/ir.schema.json and "
            "pycompose/ir/generated_validators.py."
        )
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify derived artifacts are up to date; exit non-zero on drift (CI).",
    )
    parser.add_argument(
        "--app",
        type=Path,
        metavar="DIR",
        help=(
            "Generate only the components DIR uses, into DIR itself (ADR-0014). "
            "Discovery is by name in the AST; an app that stops referencing a "
            "component stops shipping it."
        ),
    )
    args = parser.parse_args(argv)
    if args.app is not None:
        return build_app(args.app, check=args.check)
    registry = load_registry()
    artifacts = {
        IR_SCHEMA_PATH: render_ir_schema(registry),
        BUNDLED_SCHEMA_PATH: render_ir_schema(registry),
        BUNDLED_CATALOG_PATH: SCHEMA_PATH.read_text(encoding="utf-8"),
        VALIDATORS_PATH: render_validators(registry),
        PAYLOADS_PATH: render_payloads(registry),
        KOTLIN_MODELS_PATH: render_kotlin_models(registry),
        KOTLIN_REGISTRY_PATH: render_kotlin_registry(registry),
        PYTHON_COMPONENTS_PATH: render_python_components(registry),
        PYTHON_EXPORTS_PATH: render_python_exports(registry),
        ROOT / "pycompose/values.py": render_values(registry),
        KOTLIN_MODELS_PATH.with_name("ValueModels.kt"): render_models(registry),
        ROOT / KOTLIN_VALUES_RELATIVE: render_native(registry),
    }
    adapters = render_generated_adapters(registry)
    if adapters:
        artifacts[KOTLIN_ADAPTERS_PATH] = adapters
    _mirror_template(artifacts)
    for fixture in sorted((ROOT / "pycompose/testing/fixtures").glob("*.json")):
        relative = Path("ir/src/test/resources") / fixture.name
        contents = fixture.read_text(encoding="utf-8")
        artifacts[ROOT / "android" / relative] = contents
        artifacts[ROOT / "pycompose/templates/android" / relative] = contents
    if args.check:
        drifted = [
            str(artifact)
            for artifact, expected in artifacts.items()
            if _read(artifact) != expected
        ]
        if drifted:
            for artifact in drifted:
                print(
                    f"gen.py: drift detected: {artifact} is out of date",
                    file=sys.stderr,
                )
            return 1
        return 0
    for path, content in artifacts.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    print(f"gen.py: regenerated {len(artifacts)} artifact(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
