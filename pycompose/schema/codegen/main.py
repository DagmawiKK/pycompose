"""The catalog as shipped in the wheel, for an app with no repo checkout.

``ROOT`` only exists in a source checkout. An app generated from an installed
``pycompose`` has no ``schema/components.json`` above it, and no ``android/`` to
write into -- it generates its slice into its own tree -- but it does still need
the catalog, so the package carries a copy.
"""

