"""Render the pin's API surface as text, one declaration per line.

An upgrade's API change then reads as an ordinary diff of two committed files,
the way AndroidX reviews its own API. The surface is what the catalog can
reach: every component overload, and the support declarations their types
require. Artifacts and their versions stay in the header, so a version bump
with no API change leaves every line unchanged. Names drop two prefixes every
line would repeat: ``androidx.compose.`` and the ``kotlin.`` of built-in
types (``Unit``, ``Boolean``); ``kotlin.collections.List`` keeps its package.
"""

from __future__ import annotations

from pycompose.compiler.classpath_dump import Inventory
from pycompose.compiler.classpath_types import (
    COMPOSABLE,
    EXTENSION,
    Declaration,
    KotlinType,
)

KEYWORDS = {"function": "fun", "property": "val", "constructor": "constructor"}


def name_text(classifier: str) -> str:
    """Spell a classifier as the file abbreviates it.

    Args:
        classifier: The slash-separated JVM-style classifier.

    Returns:
        The dotted name without the prefixes every line would repeat.
    """
    name = classifier.replace("/", ".")
    if name.startswith("androidx.compose."):
        return name.removeprefix("androidx.compose.")
    head, _, tail = name.partition(".")
    if head == "kotlin" and "." not in tail:
        return tail
    return name


def type_text(kind: KotlinType) -> str:
    """Render one structured Kotlin type.

    Args:
        kind: The type.

    Returns:
        Its Kotlin spelling, fully qualified.
    """
    name = name_text(kind.classifier)
    arguments = [
        "*" if argument is None else _variance(variance) + type_text(argument)
        for variance, argument in kind.arguments
    ]
    function = kind.classifier.startswith(
        ("kotlin/Function", "kotlin/coroutines/SuspendFunction")
    )
    if function and kind.arguments:
        values, result = arguments[:-1], arguments[-1]
        receiver = ""
        if EXTENSION in kind.annotations and values:
            receiver, values = values[0] + ".", values[1:]
        text = f"{receiver}({', '.join(values)}) -> {result}"
        if kind.suspend:
            text = "suspend " + text
        if COMPOSABLE in kind.annotations:
            text = "@Composable " + text
        return f"({text})?" if kind.nullable else text
    if arguments:
        name += f"<{', '.join(arguments)}>"
    return name + ("?" if kind.nullable else "")


def _variance(variance: str | None) -> str:
    return {"IN": "in ", "OUT": "out "}.get(variance or "", "")


def line(declaration: Declaration) -> str:
    """Render one declaration as its signature line.

    Args:
        declaration: The pinned declaration.

    Returns:
        The owner and the Kotlin signature.
    """
    document = declaration.document
    words = []
    if declaration.composable:
        words.append("@Composable")
    if document.get("inline"):
        words.append("inline")
    if document.get("suspend"):
        words.append("suspend")
    words.append(KEYWORDS.get(document.get("declarationKind", ""), "fun"))
    context = ", ".join(type_text(t) for t in declaration.context_receivers)
    receiver = (
        type_text(declaration.receiver) + "."
        if declaration.receiver is not None
        else ""
    )
    parameters = ", ".join(
        ("vararg " if p.vararg_type is not None else "")
        + f"{p.name}: {type_text(p.vararg_type or p.type)}"
        + (" = …" if p.has_default else "")
        for p in declaration.parameters
    )
    signature = (
        (f"context({context}) " if context else "")
        + " ".join(words)
        + f" {receiver}{declaration.name}({parameters}): "
        + type_text(declaration.return_type)
    )
    return f"{name_text(declaration.owner)} {signature}"


def render(found: Inventory) -> str:
    """Render the signature file for one pin.

    Args:
        found: The pinned inventory.

    Returns:
        The file's text: a header naming the pin, then sorted lines.
    """
    surface = {
        (d.artifact, d.owner, d.jvm_name, d.jvm_descriptor): d
        for d in (*found.ui, *found.required_support)
    }.values()
    artifacts = sorted({d.artifact for d in surface})
    header = [
        f"# Compose API surface the catalog can reach, BOM {found.bom}, "
        f"compiler {found.compiler}",
        "# Generated by python -m pycompose.compiler generate; never edited.",
        *(f"# artifact {artifact}" for artifact in artifacts),
    ]
    return "\n".join([*header, *sorted(line(d) for d in surface)]) + "\n"
